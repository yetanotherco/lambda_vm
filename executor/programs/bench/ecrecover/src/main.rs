//! ecrecover bench guest — phase H.
//!
//! Drives the REAL shipping path: `LambdaVmEcsmCrypto::secp256k1_ecrecover`,
//! i.e. guest `(r, v)` decompression -> `ecsm_lincomb2` ecall -> ECSM2/ECDAS2 ->
//! `keccak256(pk)`. Not a synthetic ECSM ladder, so the number reflects what
//! actually ships.
//!
//! Private input selects the workload — ONE ELF serves every configuration, so
//! A/B arms compare identical code:
//!   byte 0      : case. 0 = mean corpus (8 real RFC 6979 signatures, cycled),
//!                 1 = worst case (u1, u2) = (2^255, 2^255 - 1), 514 chain rows.
//!   bytes 1..3  : signature count, little-endian u16 (0 is treated as 1).
//!
//! Commits the XOR of every recovered address. That is a deterministic function
//! of the workload, so the two A/B arms MUST commit identical bytes — which is
//! the cross-check that the switch did not change results.
//!
//! NOTE the fallback trap: on a non-zero accelerator status the provider falls
//! back to pure-Rust `lincomb`, which returns the SAME answer. Output equality
//! therefore cannot detect it — only the cell slope can. See BENCH.md.

