static MEAN: [&Case; 8] = [&SIG0, &SIG1, &SIG2, &SIG3, &SIG4, &SIG5, &SIG6, &SIG7];

pub fn main() {
    let input = syscalls::syscalls::get_private_input_slice();
    let case = input.first().copied().unwrap_or(0);
    let count = u16::from_le_bytes([
        input.get(1).copied().unwrap_or(1),
        input.get(2).copied().unwrap_or(0),
    ])
    .max(1) as usize;

    let crypto = LambdaVmEcsmCrypto;
    let mut acc = [0u8; 32];
    for i in 0..count {
        let c: &Case = if case == 1 { &WORST } else { MEAN[i % MEAN.len()] };
        match crypto.secp256k1_ecrecover(&c.sig, c.recid, &c.msg) {
            Ok(addr) => {
                for (a, b) in acc.iter_mut().zip(addr.iter()) {
                    *a ^= *b;
                }
            }
            // Recovery failure would silently shrink the workload; make it
            // visible in the committed output instead.
            Err(_) => acc[0] ^= 0xFF,
        }
    }
    syscalls::syscalls::commit(&acc);
}
