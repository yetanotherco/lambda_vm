// Tables 2-4 — THE RUST ORACLE. miden publishes no RPX known-answer table
// (rpx.rs "PROVENANCE"), so the host `Rpx256` is the oracle the kernel is
// pinned to. Printed by `prover/tests/rpx_host_kat_vectors.rs`:
//
//   cargo test -p lambda-vm-prover --test rpx_host_kat_vectors -- --ignored --nocapture
//
// and pasted verbatim between the `>>> BEGIN` / `<<< END` markers. Inputs are
// derived there from fixed seeds and printed next to the outputs, so this file
// is self-contained. All values are canonical (`< p`).
//
//   Table 2 — the bare permutation: all-zero, all-(p−1), `0..12`, alternating,
//             two one-hot lanes, four seeded random states, and the row named
//             "canonicalisation witness" — an input whose output lane 0 is the
//             raw twin `p + 1` before the kernel's final canonicalisation loop
//             (derived by `rpx_canon_witness.py`; the harness replays it).
//   Table 3 — the leaf sponge (`algebraic_commit::sponge_leaf`) at 0, 1, 7, 8,
//             9, 16 and 17 felts; `felts[]` is zero beyond `len`.
//   Table 4 — the parent `compress(l, r)`.
//   Table 5 — the proof-of-work grind: the inner hash's four BIG-endian felts
//             and the smallest valid nonce, at three grinding factors, taken
//             through the production predicate `stark::grinding::is_valid_nonce`
//             over `GrindingDigest<RpxStarkHash>`; `le_nonce` is what the same
//             kernel answers on the LITTLE-endian reading of the same inner
//             hash, and must differ.
// ---------------------------------------------------------------------------
struct RpxPermutationVector {
    const char *name;
    uint64_t input[12];
    uint64_t output[12];
};

inline constexpr int RPX_LEAF_KAT_MAX_FELTS = 17;
struct RpxLeafVector {
    uint32_t len;
    uint64_t felts[RPX_LEAF_KAT_MAX_FELTS];
    uint64_t digest[4];
};

struct RpxParentVector {
    const char *name;
    uint64_t left[4];
    uint64_t right[4];
    uint64_t digest[4];
};

struct RpxGrindVector {
    uint8_t seed_byte;        // the 32-byte grinding seed is this byte, repeated
    uint8_t factor;           // limit = 1 << (64 - factor)
    uint64_t inner_felts[4];  // BIG-endian reading of the 32-byte inner hash
    uint64_t nonce;           // the smallest nonce the host predicate accepts
    uint64_t le_nonce;        // the same kernel's answer on the LE reading
};

