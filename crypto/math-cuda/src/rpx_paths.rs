//! Which RPX device path each of three choices takes: the Merkle tree tops,
//! the proof-of-work grind, and the permutation's field multiply.
//!
//! Each choice has its value stated ONCE, as a `*_DEFAULT` constant below. A
//! pipeline that needs one of them the other way flips that constant, one
//! line, the way `lfm::chunking`'s `HASH_SPLIT_DEFAULT` differs between the
//! two pipelines.
//!
//! Every setting produces the same bytes: the nodes, roots, grind nonces and
//! digests are the other path's, which `prover/tests/rpx_device_paths.rs` pins
//! path against path and against the host oracle (the other paths stay
//! reachable through their typed entry points). These choose speed, never the
//! proof: a block proved either way has the same program ids.

// `LIMB_PERMUTE_VARIANT`: the permutation variant of the default RPX cubin.
// Generated by build.rs from the variant it compiles, so the two cannot drift.
include!(concat!(env!("OUT_DIR"), "/rpx_variants.rs"));

/// The Merkle tops: levels of up to 16,384 pairs through
/// `rpx_merkle_level_warp` (a half-warp per parent) and the last 64 pairs
/// through one `rpx_merkle_tail_warp` block, in every RPX tree walk (the STARK
/// trace, aux, composition and FRI trees, the WHIR trees and their query-time
/// rebuilds). Off: `rpx_merkle_level` at every level and `rpx_merkle_tail`
/// from 128 pairs up.
pub const WARP_MERKLE_DEFAULT: bool = true;

/// The RPX grind: `rpx_grind_search_queue`, warps claiming 32 nonces at a time
/// from a queue head, on a grid of multiprocessors × the kernel's occupancy.
/// Off: `rpx_grind_search`'s stride walk on `LAMBDA_VM_GRIND_GRID` blocks. The
/// same smallest nonce either way.
pub const GRIND_QUEUE_DEFAULT: bool = true;

/// The permutation's field multiply: every RPX kernel from
/// `rpx_v<LIMB_PERMUTE_VARIANT>.cubin` (32-bit limb multiplies with carry
/// chains, `square_n` unrolled by four). Off: `rpx_v0.cubin`, the 64-bit
/// multiply. Both cubins are always built, so flipping this is one line.
pub const LIMB_PERMUTE_DEFAULT: bool = true;

/// Whether RPX Merkle walks take the half-warp levels and the one-block tail.
pub fn warp_merkle() -> bool {
    WARP_MERKLE_DEFAULT
}

/// Whether the RPX grind takes the work-queue kernel.
pub fn grind_queue() -> bool {
    GRIND_QUEUE_DEFAULT
}

/// Whether the RPX module loads at [`LIMB_PERMUTE_VARIANT`] rather than at
/// variant 0.
pub fn limb_permute() -> bool {
    LIMB_PERMUTE_DEFAULT
}

#[cfg(test)]
mod tests {
    use super::LIMB_PERMUTE_VARIANT;

    /// The variant the limb cubin is built at is the one the bench measured
    /// fastest (0.8128 of variant 0 per permutation on the 5090): limb
    /// multiply (1) plus `square_n` unrolled by four (4). Another variant is
    /// another measurement, not a rename.
    #[test]
    fn the_limb_permutation_is_variant_five() {
        assert_eq!(LIMB_PERMUTE_VARIANT, 5);
    }
}
