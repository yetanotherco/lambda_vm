//! Poseidon-original ("Poseidon1") over Goldilocks at width 12 — the hash
//! matrix's first real candidate behind the `LFM_HASH` socket.
//!
//! # Why this hash and not Poseidon2
//!
//! Poseidon2 is BROKEN (eprint 2026/306 exploits the structure of its linear
//! layers) and must never be built here. Poseidon-original is the same S-box
//! family with a dense MDS that lacks the exploited structure, and it is where
//! the ecosystem moved.
//!
//! # Parameter provenance — READ THIS BEFORE TRUSTING A MEASUREMENT
//!
//! Parameters are taken from the vendored Plonky3 tree,
//! `others/Plonky3/goldilocks/src/poseidon1.rs` @ 4aed8fe4, which documents
//! them as generated by the Grain LFSR of the Poseidon paper (Appendix E) with
//! `field_type=1, alpha=7 (exp_flag=0), n=64, t=12, R_F=8, R_P=22`, via
//! `poseidon/generate_constants.py --field goldilocks --width 12`:
//!
//! - `ALPHA = 7` — the smallest valid exponent, because Goldilocks has
//!   `p - 1 = 2^32 · 3 · 5 · 17 · 257 · 65537`, so neither 3 nor 5 is coprime to
//!   `p - 1`. **A cube S-box is not a permutation over this field**, which is
//!   why the in-tree HADES skeleton in `crypto/crypto/src/hash/poseidon/` can
//!   never serve as an oracle: it hardcodes `x^3`.
//! - `R_F = 8` full rounds (4 initial + 4 terminal), `R_P = 22` partial.
//! - The MDS matrix is CIRCULANT with first row `MDS_CIRC_ROW`.
//!
//! ⚠ **Ship-grade parameter selection is a separate cryptographic decision for
//! the ecosystem and is NOT settled by this measurement.** These parameters are
//! adequate to measure the AIR's SHAPE — cells depend on round counts and the
//! S-box degree, not on the numeric values of the constants — and they come from
//! a published generator, but choosing what to ship is not ours.
//!
//! # Oracle
//!
//! [`tests::the_permutation_matches_the_plonky3_known_answer_vector`] pins the
//! whole permutation against Plonky3's own known-answer test
//! (`goldilocks/src/poseidon1.rs::test_poseidon_goldilocks_width_12`), an
//! EXTERNAL vector we did not compute. That is the differential this module
//! rests on.

