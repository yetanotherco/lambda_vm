    /// The S-box exponent must be coprime to `p - 1`, or the S-box is not a
    /// permutation. This is the exact trap the in-tree HADES skeleton falls into
    /// with its hardcoded `x^3`, so the property is asserted rather than trusted.
    #[test]
    fn the_sbox_exponent_is_coprime_to_the_group_order() {
        // Goldilocks: p = 2^64 - 2^32 + 1, and p - 1 = 2^32 · 3 · 5 · 17 · 257 · 65537.
        const P_MINUS_ONE: u128 = (1u128 << 64) - (1u128 << 32);
        fn gcd(a: u128, b: u128) -> u128 {
            if b == 0 { a } else { gcd(b, a % b) }
        }
        assert_eq!(
            gcd(ALPHA as u128, P_MINUS_ONE),
            1,
            "x^{ALPHA} must be a permutation over Goldilocks"
        );
        for bad in [3u128, 5] {
            assert_ne!(
                gcd(bad, P_MINUS_ONE),
                1,
                "{bad} divides p-1, so x^{bad} is NOT a permutation — the skeleton's bug"
            );
        }
    }

