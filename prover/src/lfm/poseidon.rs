/// Poseidon-original over Goldilocks, width 12 — a real cryptographic hash
/// behind the `LFM_HASH` contract, replacing `TestPermutation`.
pub struct PoseidonGoldilocks;

impl PoseidonGoldilocks {
    /// `x^7` by square-and-multiply: `x^2`, `x^3 = x^2 * x`, `x^7 = (x^3)^2 * x`.
    ///
    /// Written in exactly the association the AIR's degree-3 lowering uses, so
    /// the executor and the chip agree by construction rather than by luck.
    fn sbox(x: &FE) -> FE {
        let x2 = x * x;
        let x3 = &x2 * x;
        let x6 = &x3 * &x3;
        &x6 * x
    }

    /// The circulant MDS product.
    fn mds(state: &[FE; HASH_STATE_FELTS]) -> [FE; HASH_STATE_FELTS] {
        core::array::from_fn(|i| {
            let mut acc = FE::zero();
            for (j, s) in state.iter().enumerate() {
                let c = FE::from(MDS_CIRC_ROW[(j + HASH_STATE_FELTS - i) % HASH_STATE_FELTS]);
                acc += c * s;
            }
            acc
        })
    }

    fn add_round_constants(state: &mut [FE; HASH_STATE_FELTS], round: usize) {
        for (k, s) in state.iter_mut().enumerate() {
            *s += FE::from(ROUND_CONSTANTS[round][k]);
        }
    }
}

impl LfmHasher for PoseidonGoldilocks {
    fn permute(&self, state: [FE; HASH_STATE_FELTS]) -> [FE; HASH_STATE_FELTS] {
        let mut s = state;
        let mut round = 0;
        for _ in 0..HALF_FULL_ROUNDS {
            Self::add_round_constants(&mut s, round);
            for lane in s.iter_mut() {
                *lane = Self::sbox(lane);
            }
            s = Self::mds(&s);
            round += 1;
        }
        for _ in 0..PARTIAL_ROUNDS {
            Self::add_round_constants(&mut s, round);
            s[0] = Self::sbox(&s[0]);
            s = Self::mds(&s);
            round += 1;
        }
        for _ in 0..HALF_FULL_ROUNDS {
            Self::add_round_constants(&mut s, round);
            for lane in s.iter_mut() {
                *lane = Self::sbox(lane);
            }
            s = Self::mds(&s);
            round += 1;
        }
        debug_assert_eq!(round, NUM_ROUNDS, "every round constant row is consumed");
        s
    }

    /// The capacity cell for `Compress` mode.
    ///
    /// ⚠ ZERO capacity, i.e. the plain sponge compression of `[a ‖ b ‖ 0]`.
    /// Domain separation is a cryptographic decision of the same class as
    /// parameter selection and is deliberately NOT invented here; a shipped
    /// design may well want a nonzero, length- or position-dependent IV.
    fn compress_iv(&self) -> LfmWord {
        [FE::zero(), FE::zero(), FE::zero(), FE::zero()]
    }
}

