//! The four sequence vectors, and what each one is for.

use super::whir_transcript_kats::{Script, Step, run};

/// K1 — ORDER. Distinct, asymmetric values, so swapping any two absorbs moves
/// the result. A script of equal values would pass a swap.
const K1_ORDER: Script = Script {
    name: "order",
    steps: &[
        Step::AbsorbBytes {
            seed: 0x11,
            len: 32,
        },
        Step::AbsorbExt { seed: 0x2222_2222 },
        Step::SampleExt,
        Step::AbsorbBytes { seed: 0x33, len: 8 },
        Step::SampleExt,
        Step::SampleU64 { bound: 1 << 20 },
    ],
};

/// K2 — WIDTH AND PADDING. Every length class mod 8 and mod 64, because the
/// leaf sponge's padding flag is `len mod 8` and its block is 64 bytes. A
/// trailing partial group zero-extended on the wrong side lands here.
const K2_WIDTH: Script = Script {
    name: "width",
    steps: &[
        Step::AbsorbBytes { seed: 0x41, len: 0 },
        Step::SampleExt,
        Step::AbsorbBytes { seed: 0x42, len: 1 },
        Step::SampleExt,
        Step::AbsorbBytes { seed: 0x43, len: 7 },
        Step::SampleExt,
        Step::AbsorbBytes { seed: 0x44, len: 8 },
        Step::SampleExt,
        Step::AbsorbBytes { seed: 0x45, len: 9 },
        Step::SampleExt,
        Step::AbsorbBytes {
            seed: 0x46,
            len: 63,
        },
        Step::SampleExt,
        Step::AbsorbBytes {
            seed: 0x47,
            len: 64,
        },
        Step::SampleExt,
        Step::AbsorbBytes {
            seed: 0x48,
            len: 65,
        },
        Step::SampleExt,
        Step::AbsorbBytes {
            seed: 0x49,
            len: 72,
        },
        Step::SampleExt,
    ],
};

/// K3 — CHAIN ADVANCE. Consecutive draws with no absorb between them. A
/// squeeze re-absorbs its own output; drop that and every draw after the first
/// repeats, which one squeeze cannot show.
const K3_CHAIN: Script = Script {
    name: "chain",
    steps: &[
        Step::AbsorbBytes {
            seed: 0x51,
            len: 32,
        },
        Step::SampleExt,
        Step::SampleExt,
        Step::SampleExt,
        Step::SampleExt,
        Step::SampleExt,
        Step::SampleExt,
    ],
};

/// K4 — SAMPLER OFFSET. An asymmetric interleaving of the two samplers and an
/// absorb. An extension element takes three of a squeeze's four candidates and
/// an absorb discards the rest, so a one-candidate slip still produces
/// plausible field elements and is invisible to anything but pinned values.
const K4_OFFSET: Script = Script {
    name: "offset",
    steps: &[
        Step::AbsorbBytes {
            seed: 0x61,
            len: 24,
        },
        Step::SampleU64 { bound: 1 << 23 },
        Step::SampleExt,
        Step::SampleU64 { bound: 1 << 19 },
        Step::SampleU64 { bound: 1 << 19 },
        Step::SampleExt,
        Step::AbsorbBytes {
            seed: 0x62,
            len: 32,
        },
        Step::SampleExt,
        Step::SampleU64 { bound: 4 },
    ],
};

const SCRIPTS: &[&Script] = &[&K1_ORDER, &K2_WIDTH, &K3_CHAIN, &K4_OFFSET];

/// Prints the vectors in the form the table below takes. Run after a
/// deliberate change to the transcript, never to make a red test green.
#[test]
#[ignore = "generator, not a test"]
fn print_whir_transcript_vectors() {
    for s in SCRIPTS {
        let o = run(s);
        let ext: Vec<String> = o
            .ext
            .iter()
            .map(|e| {
                let [a, b, c] = *e.value();
                format!("({}, {}, {})", a.value(), b.value(), c.value())
            })
            .collect();
        println!("// {}", s.name);
        println!("state {}", hex(&o.state));
        println!("ext   [{}]", ext.join(", "));
        println!("u64s  {:?}\n", o.u64s);
    }
}

fn hex(b: &[u8; 32]) -> String {
    b.iter().map(|x| format!("{x:02x}")).collect()
}

/// ★ The vectors. GENERATED by the test above — recordings of this
/// transcript, not a specification of it (see the module header).
