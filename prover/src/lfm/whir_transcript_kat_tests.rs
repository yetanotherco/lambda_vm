#[test]
fn the_whir_transcript_scripts_reproduce_their_vectors() {
    for (s, want) in SCRIPTS.iter().zip(VECTORS) {
        assert_eq!(
            s.name, want.name,
            "the script table and the vector table must agree in order"
        );
        let got = run(s);
        let flat: Vec<u64> = got
            .ext
            .iter()
            .flat_map(|e| {
                let [a, b, c] = *e.value();
                [*a.value(), *b.value(), *c.value()]
            })
            .collect();
        assert_eq!(
            flat.as_slice(),
            want.ext,
            "{}: a sampled extension element moved — the draw schedule or the \
             buffer offset changed",
            want.name
        );
        assert_eq!(
            got.u64s.as_slice(),
            want.u64s,
            "{}: a sampled u64 moved",
            want.name
        );
        assert_eq!(
            hex(&got.state),
            want.state,
            "{}: the transcript's sequence moved. If that was deliberate, rerun \
             `print_whir_transcript_vectors` and say in the commit which absorb \
             or draw changed; if it was not, the emitter and the host have \
             diverged",
            want.name
        );
    }
}

/// ⚠ An edge the vectors above happen to record, worth its own name.
///
/// `sponge_leaf_bytes` returns the capacity's low lanes without permuting when
/// there is nothing to absorb, and those lanes are zero — so squeezing a
/// transcript that has absorbed nothing yields the ZERO digest and hence a zero
/// challenge. Production never reaches it: every WHIR transcript absorbs its
/// statement tag before drawing anything. This test is here so that a path
/// which one day samples first fails loudly rather than drawing a constant.
#[test]
fn an_empty_rpx_transcript_squeezes_to_zero_which_production_never_reaches() {
    let empty = Script {
        name: "empty",
        steps: &[Step::SampleExt],
    };
    let o = run(&empty);
    let [a, b, c] = *o.ext[0].value();
    assert_eq!(
        (*a.value(), *b.value(), *c.value()),
        (0, 0, 0),
        "the empty squeeze is documented as the un-permuted capacity; if it is \
         no longer zero the sponge's empty case changed"
    );
    // And the guard that makes it harmless: a statement tag first.
    let tagged = Script {
        name: "tagged",
        steps: &[
            Step::AbsorbBytes {
                seed: 0x71,
                len: 41,
            },
            Step::SampleExt,
        ],
    };
    let t = run(&tagged);
    let [a, b, c] = *t.ext[0].value();
    assert_ne!(
        (*a.value(), *b.value(), *c.value()),
        (0, 0, 0),
        "a challenge drawn after a statement absorb must not be the zero element"
    );
}

/// K3's own property, which no single pinned value can express: a squeeze
/// re-absorbs its output, so consecutive draws cannot repeat.
#[test]
fn consecutive_draws_never_repeat_because_a_squeeze_advances_the_chain() {
    let o = run(&K3_CHAIN);
    for i in 0..o.ext.len() {
        for j in (i + 1)..o.ext.len() {
            assert_ne!(
                o.ext[i], o.ext[j],
                "draws {i} and {j} are equal — the squeeze did not chain its \
                 output back in, and every draw after the first is a repeat"
            );
        }
    }
}
