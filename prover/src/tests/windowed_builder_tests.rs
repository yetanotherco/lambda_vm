/// The whole-run KECCAK_RND table cut into tables of `rows` rows — rows
/// `[k·rows, (k+1)·rows)`, as the block proof splits it.
fn split_keccak_rnd(t: &Traces, per: usize) -> Vec<Table> {
    t.keccak_rnds
        .iter()
        .flat_map(|table| {
            let width = table.main_table.width;
            let all = rows(table);
            if all.len() <= per {
                return vec![rebuild(&all, width)];
            }
            all.chunks(per).map(|chunk| rebuild(chunk, width)).collect()
        })
        .collect()
}

fn rebuild(rows: &[Vec<FieldElement<GoldilocksField>>], width: usize) -> Table {
    TraceTable::new_main(rows.iter().flatten().copied().collect(), width, 1)
}

/// A slice of KECCAK_RND rows built from the ops that reach it is that slice of
/// the whole table, wherever the slice cuts an op's 24 rows.
#[test]
fn keccak_rnd_rows_are_slices_of_the_whole_table() {
    use crate::tables::keccak_rnd::{
        KeccakRoundOperation, generate_keccak_rnd_rows, generate_keccak_rnd_trace,
    };
    let ops: Vec<KeccakRoundOperation> = (0..11u64)
        .map(|i| KeccakRoundOperation {
            timestamp: 100 + 3 * i,
            input: core::array::from_fn(|j| i.wrapping_mul(0x9e37_79b9_7f4a_7c15) ^ j as u64),
            output: [0; 25],
        })
        .collect();
    let whole = rows(&generate_keccak_rnd_trace(&ops));
    for (skip, len) in [
        (0, 32),
        (32, 32),
        (50, 64),
        (23, 1),
        (100, 156),
        (256, 0),
        (200, 56),
    ] {
        let slice = rows(&generate_keccak_rnd_rows(&ops, skip, len));
        assert_eq!(slice.len(), len);
        assert!(
            slice[..] == whole[skip..skip + len],
            "rows {skip}..{}",
            skip + len
        );
    }
}

/// ★ With KECCAK_RND cut into chunks, the windowed build streams them and is the
/// whole-run build with KECCAK_RND split the same way, table for table; at
/// one-cycle windows it did stream some.
#[test]
fn windowed_streams_keccak_rnd_as_the_split_whole_run_table() {
    let max_rows = MaxRowsConfig::small();
    for name in ["test_keccak", "test_keccak_multi"] {
        let (program, logs) = run(name);
        let mut reference = whole(&program, &logs, &max_rows);
        for per in [32usize, 64, 128] {
            let split = split_keccak_rnd(&reference, per);
            for window in [1, 7, 33] {
                let mut builder = WindowedTraceBuilder::new(&program, &[], &max_rows)
                    .expect("the builder")
                    .keccak_rnd_chunks(per)
                    .expect("a chunk size");
                let body = logs.len() - 1;
                let cut = body - body % window;
                let mut chunks = Vec::new();
                for w in logs[..cut].chunks(window) {
                    chunks.extend(builder.push(w).expect("a window"));
                }
                let streamed = chunks
                    .iter()
                    .filter(|c| c.table == StreamTable::KeccakRnd)
                    .count();
                let mut traces = builder.finish(&logs[cut..]).expect("the last window");
                traces.insert_streamed(chunks).expect("placeholders");
                same_list(
                    &format!("{name} KECCAK_RND/{per} window {window}"),
                    &split,
                    &traces.keccak_rnds,
                );
                // One-cycle windows push every cycle but the last, so every
                // chunk the ops fill before the run ends streams.
                let full = split.iter().filter(|t| t.main_table.height == per).count();
                if window == 1 && full > 1 {
                    assert!(streamed > 0, "{name}, rows {per}: none streamed");
                }
                // Every other table is the whole-run one.
                let keccak =
                    std::mem::replace(&mut reference.keccak_rnds, traces.keccak_rnds.clone());
                same_traces(&reference, &traces);
                reference.keccak_rnds = keccak;
            }
        }
    }
}

/// With KECCAK_RND built as its tables at the finish alone, the windowed build
/// hands none out and is the whole-run build with KECCAK_RND split the same
/// way, table for table — the split's copy without the copy.
#[test]
fn windowed_builds_keccak_rnd_at_finish_as_the_split_whole_run_table() {
    let max_rows = MaxRowsConfig::small();
    for name in ["test_keccak", "test_keccak_multi"] {
        let (program, logs) = run(name);
        let mut reference = whole(&program, &logs, &max_rows);
        for per in [32usize, 64, 128] {
            let split = split_keccak_rnd(&reference, per);
            for window in [1, 33] {
                let mut builder = WindowedTraceBuilder::new(&program, &[], &max_rows)
                    .expect("the builder")
                    .keccak_rnd_chunks_at_finish(per)
                    .expect("a chunk size");
                let body = logs.len() - 1;
                let cut = body - body % window;
                let mut chunks = Vec::new();
                for w in logs[..cut].chunks(window) {
                    chunks.extend(builder.push(w).expect("a window"));
                }
                assert!(
                    chunks.iter().all(|c| c.table != StreamTable::KeccakRnd),
                    "{name}: a KECCAK_RND chunk was handed out"
                );
                let mut traces = builder.finish(&logs[cut..]).expect("the last window");
                traces.insert_streamed(chunks).expect("placeholders");
                same_list(
                    &format!("{name} KECCAK_RND/{per} at the finish, window {window}"),
                    &split,
                    &traces.keccak_rnds,
                );
                let keccak =
                    std::mem::replace(&mut reference.keccak_rnds, traces.keccak_rnds.clone());
                same_traces(&reference, &traces);
                reference.keccak_rnds = keccak;
            }
        }
    }
    assert!(
        WindowedTraceBuilder::new(&run("test_keccak").0, &[], &max_rows)
            .expect("the builder")
            .keccak_rnd_chunks_at_finish(16)
            .is_err(),
        "16 rows is under the 32 a KECCAK_RND op's rows need"
    );
}

/// Every LT op with its multiplicity summed over all of `lts`' chunks: what LT's
/// constraints and the bus see, whichever chunk holds an op.
fn lt_multiplicities(lts: &[Table]) -> std::collections::BTreeMap<Vec<u64>, u64> {
    let mu = crate::tables::lt::cols::MU;
    let mut out = std::collections::BTreeMap::new();
    for table in lts {
        for row in rows(table) {
            let m = row[mu].canonical();
            if m == 0 {
                continue;
            }
            let key: Vec<u64> = row
                .iter()
                .enumerate()
                .filter(|(c, _)| *c != mu)
                .map(|(_, v)| v.canonical())
                .collect();
            *out.entry(key).or_insert(0) += m;
        }
    }
    out
}

/// ★ With each window's MEMW-derived LT ops streamed (the block path), every
/// table but LT is the whole-run build's, LT has as many chunks, and every LT
/// op carries its whole-run multiplicity summed over the chunks — though the
/// chunks hold other ops. Dropping one row of one chunk breaks that equality,
/// so it is what the test checks. And it streams more LT chunks than without.
#[test]
fn windowed_streams_memw_lt_with_the_whole_run_lt_multiplicities() {
    let max_rows = MaxRowsConfig::small();
    let mut more_streamed = false;
    for name in ["all_instructions_64", "test_keccak_multi"] {
        let (program, logs) = run(name);
        let mut reference = whole(&program, &logs, &max_rows);
        let want = lt_multiplicities(&reference.lts);
        for window in [1, 7, 33] {
            let mut builder = WindowedTraceBuilder::new(&program, &[], &max_rows)
                .expect("the builder")
                .stream_memw_lt();
            let body = logs.len() - 1;
            let cut = body - body % window;
            let mut chunks = Vec::new();
            for w in logs[..cut].chunks(window) {
                chunks.extend(builder.push(w).expect("a window"));
            }
            let lt_streamed = chunks.iter().filter(|c| c.table == StreamTable::Lt).count();
            let mut traces = builder.finish(&logs[cut..]).expect("the last window");
            traces.insert_streamed(chunks).expect("placeholders");
            assert_eq!(
                traces.lts.len(),
                reference.lts.len(),
                "{name}/{window}: LT chunks"
            );
            assert!(
                lt_multiplicities(&traces.lts) == want,
                "{name}/{window}: LT multiplicities"
            );
            let plain_lt = {
                let mut builder =
                    WindowedTraceBuilder::new(&program, &[], &max_rows).expect("the builder");
                logs[..cut]
                    .chunks(window)
                    .flat_map(|w| builder.push(w).expect("a window"))
                    .filter(|c| c.table == StreamTable::Lt)
                    .count()
            };
            assert!(
                lt_streamed >= plain_lt,
                "{name}/{window}: fewer LT chunks streamed"
            );
            more_streamed |= lt_streamed > plain_lt;
            // Every other table is the whole-run one.
            let lts = std::mem::replace(&mut reference.lts, traces.lts.clone());
            same_traces(&reference, &traces);
            reference.lts = lts;

            // The mutation: one row of one chunk dropped (its multiplicity zeroed).
            let mut dropped = traces.lts.clone();
            let mu = crate::tables::lt::cols::MU;
            let (k, row) = dropped
                .iter()
                .enumerate()
                .find_map(|(k, t)| {
                    (0..t.main_table.height)
                        .find(|&r| t.main_table.get(r, mu).canonical() != 0)
                        .map(|r| (k, r))
                })
                .expect("a real LT row");
            dropped[k]
                .main_table
                .set(row, mu, FieldElement::<GoldilocksField>::zero());
            assert!(
                lt_multiplicities(&dropped) != want,
                "{name}/{window}: a dropped row must change the multiplicities"
            );
        }
    }
    assert!(
        more_streamed,
        "the MEMW-derived LT ops never streamed a chunk more"
    );
}

/// [`WindowedTraceBuilder::held_streamed_ops`]'s report.
type Held = [(usize, usize); 8];

/// A windowed build over windows of `window` cycles with the builder `configure`
/// returns, its chunks generated by their jobs on the walker/accumulator split
/// (the block drivers' path) or through `push`; and, under
/// `drop_streamed_ops`, the most streamed ops it held after any window.
fn windowed_with(
    program: &Elf,
    logs: &[Log],
    max_rows: &MaxRowsConfig,
    window: usize,
    split: bool,
    configure: impl Fn(WindowedTraceBuilder<'_>) -> WindowedTraceBuilder<'_>,
) -> (Traces, Option<Held>) {
    let (traces, held, _) = windowed_streaming(program, logs, max_rows, window, split, configure);
    (traces, held)
}

/// [`windowed_with`], and the tables it streamed chunks of.
fn windowed_streaming(
    program: &Elf,
    logs: &[Log],
    max_rows: &MaxRowsConfig,
    window: usize,
    split: bool,
    configure: impl Fn(WindowedTraceBuilder<'_>) -> WindowedTraceBuilder<'_>,
) -> (Traces, Option<Held>, std::collections::BTreeSet<String>) {
    let mut builder =
        configure(WindowedTraceBuilder::new(program, &[], max_rows).expect("the builder"));
    let body = logs.len() - 1;
    let cut = body - body % window;
    let mut chunks = Vec::new();
    let mut most: Option<Held> = None;
    let mut note = |held: Option<Held>| {
        if let Some(held) = held {
            let most = most.get_or_insert([(0, 0); 8]);
            for (m, h) in most.iter_mut().zip(held) {
                *m = (m.0.max(h.0), m.1.max(h.1));
            }
        }
    };
    for w in logs[..cut].chunks(window) {
        if split {
            let (mut walker, mut accumulator) = builder.split();
            let walked = walker.walk(w).expect("a window");
            chunks.extend(
                accumulator
                    .absorb(walked)
                    .into_iter()
                    .map(|job| job.generate()),
            );
        } else {
            chunks.extend(builder.push(w).expect("a window"));
        }
        note(builder.held_streamed_ops());
    }
    let streamed = chunks.iter().map(|c| format!("{:?}", c.table)).collect();
    let mut traces = builder.finish(&logs[cut..]).expect("the last window");
    traces
        .insert_streamed(chunks)
        .expect("every chunk has a placeholder");
    (traces, most, streamed)
}

