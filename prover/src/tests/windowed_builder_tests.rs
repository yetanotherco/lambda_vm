/// ★ Dropping bounds what the builder holds: after every window each streamed
/// table holds less than a chunk of ops not handed out, and its lists take room
/// for at most a window's part more — however long the run. Keeping every
/// window would hold the run's ops, which here are many times that.
#[test]
fn dropping_the_streamed_ops_holds_less_than_a_chunk_per_table() {
    let max_rows = MaxRowsConfig::small();
    let maxes = [
        max_rows.cpu,
        max_rows.memw_register,
        max_rows.memw_aligned,
        max_rows.memw,
        max_rows.load,
        max_rows.lt,
        max_rows.shift,
        max_rows.store,
    ];
    let mut long = false;
    for name in ["bench_32k", "test_keccak_multi"] {
        let (program, logs) = run(name);
        for window in [1, 7, 33] {
            let (_, held) = windowed_with(&program, &logs, &max_rows, window, true, |b| {
                b.drop_streamed_ops().expect("before any window")
            });
            let held = held.expect("dropping reports what it holds");
            // A window's part: one CPU op per cycle; at most 256 ops of another
            // table per cycle (a keccak ECALL's memory accesses are the most a
            // cycle makes: ≈ 170 MEMW_A ops on test_keccak_multi).
            for (table, ((not_out, room), max)) in held.iter().zip(maxes).enumerate() {
                let per_cycle = if table == 0 { 1 } else { 256 };
                assert!(
                    *not_out < max,
                    "{name}/{window}: table {table} holds {not_out} ops, a full chunk"
                );
                assert!(
                    *room < max + per_cycle * window,
                    "{name}/{window}: table {table} takes room for {room} ops"
                );
            }
            // Keeping every window would hold the run's CPU ops.
            long |= logs.len() > 100 * (max_rows.cpu + window);
        }
        // Without the option nothing is reported.
        let (_, held) = windowed_with(&program, &logs, &max_rows, 7, true, |b| b);
        assert!(held.is_none());
    }
    assert!(
        long,
        "no run long enough that keeping it would fail the CPU bound"
    );
}

/// The hand-out's stamps count every chunk it handed out, table by table, and
/// the ops it copied. Handed out as the window parts they lie in (the default)
/// no chunk is copied; under `LAMBDA_VM_HANDOUT_COPY=1` a CPU chunk whose
/// window lists are each exactly a chunk moves out whole (none copied) and one
/// cut out of windows of 7 cycles is copied op for op. The tables are the same
/// every way.
#[test]
fn the_handout_stamps_count_each_tables_chunks_and_copies() {
    let max_rows = MaxRowsConfig::small();
    let (program, logs) = run("bench_32k");
    let reference = whole(&program, &logs, &max_rows);
    let copies = std::env::var("LAMBDA_VM_HANDOUT_COPY").is_ok_and(|v| v.trim() == "1");
    for (window, copied_when_copying) in [(max_rows.cpu, 0), (7, max_rows.cpu)] {
        let cpu_copied_per_chunk = if copies { copied_when_copying } else { 0 };
        let mut builder = WindowedTraceBuilder::new(&program, &[], &max_rows)
            .expect("the builder")
            .drop_streamed_ops()
            .expect("before any window");
        let body = logs.len() - 1;
        let cut = body - body % window;
        let mut chunks = Vec::new();
        let mut handed = [0usize; 9];
        for w in logs[..cut].chunks(window) {
            let (mut walker, mut accumulator) = builder.split();
            let walked = walker.walk(w).expect("a window");
            for job in accumulator.absorb(walked) {
                handed[job.table.position()] += 1;
                chunks.push(job.generate());
            }
        }
        let stamps = builder.stamps().handout;
        let streamed = builder.streamed();
        let mut traces = builder.finish(&logs[cut..]).expect("the last window");
        traces
            .insert_streamed(chunks)
            .expect("every chunk has a placeholder");
        same_traces(&reference, &traces);
        assert_eq!(stamps.chunks, handed, "window {window}: chunks per table");
        assert_eq!(stamps.chunks[StreamTable::Cpu.position()], streamed.cpu);
        assert!(
            streamed.cpu > 10,
            "window {window}: {} CPU chunks",
            streamed.cpu
        );
        assert_eq!(
            stamps.copied[StreamTable::Cpu.position()],
            streamed.cpu * cpu_copied_per_chunk,
            "window {window}: CPU ops copied"
        );
        let timed: f64 = stamps.take.iter().chain(&stamps.count).sum();
        assert!(timed > 0.0, "window {window}: nothing timed");
    }
    for (i, table) in StreamTable::ALL.iter().enumerate() {
        assert_eq!(table.position(), i);
    }
}

