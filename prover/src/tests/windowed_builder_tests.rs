type Table = TraceTable<GoldilocksField, GoldilocksExtension>;

fn run(name: &str) -> (Elf, Vec<Log>) {
    let program = Elf::load(&asm_elf_bytes(name)).expect("the ELF loads");
    let logs = Executor::new(&program, Vec::new())
        .expect("the executor starts")
        .run()
        .expect("the program runs")
        .logs;
    (program, logs)
}

fn whole(program: &Elf, logs: &[Log], max_rows: &MaxRowsConfig) -> Traces {
    Traces::from_elf_and_logs(
        program,
        logs,
        max_rows,
        &[],
        #[cfg(feature = "disk-spill")]
        stark::storage_mode::StorageMode::Ram,
    )
    .expect("the whole-run build")
}

/// The windowed build over windows of `window` cycles (the last window is the
/// rest, at least one cycle), with its streamed chunks put back; and how many
/// chunks it streamed.
fn windowed(
    program: &Elf,
    logs: &[Log],
    max_rows: &MaxRowsConfig,
    window: usize,
) -> (Traces, usize) {
    let mut builder = WindowedTraceBuilder::new(program, &[], max_rows).expect("the builder");
    let body = logs.len() - 1;
    let cut = body - body % window;
    let mut chunks = Vec::new();
    for w in logs[..cut].chunks(window) {
        chunks.extend(builder.push(w).expect("a window"));
    }
    let streamed = chunks.len();
    let mut traces = builder.finish(&logs[cut..]).expect("the last window");
    traces
        .insert_streamed(chunks)
        .expect("every chunk has a placeholder");
    (traces, streamed)
}

/// [`windowed`] through `push_jobs`, each chunk generated by its job.
fn windowed_jobs(program: &Elf, logs: &[Log], max_rows: &MaxRowsConfig, window: usize) -> Traces {
    let mut builder = WindowedTraceBuilder::new(program, &[], max_rows).expect("the builder");
    let body = logs.len() - 1;
    let cut = body - body % window;
    let mut chunks = Vec::new();
    for w in logs[..cut].chunks(window) {
        chunks.extend(
            builder
                .push_jobs(w)
                .expect("a window")
                .into_iter()
                .map(|job| job.generate()),
        );
    }
    let mut traces = builder.finish(&logs[cut..]).expect("the last window");
    traces
        .insert_streamed(chunks)
        .expect("every chunk has a placeholder");
    traces
}

/// [`windowed`] with the builder split: the walker on one thread, the
/// accumulator on another, the chunks generated by their jobs.
fn windowed_split(program: &Elf, logs: &[Log], max_rows: &MaxRowsConfig, window: usize) -> Traces {
    let mut builder = WindowedTraceBuilder::new(program, &[], max_rows).expect("the builder");
    let body = logs.len() - 1;
    let cut = body - body % window;
    let chunks = {
        let (mut walker, mut accumulator) = builder.split();
        std::thread::scope(|scope| {
            let (tx, rx) = std::sync::mpsc::sync_channel(2);
            let walking = scope.spawn(move || {
                for w in logs[..cut].chunks(window) {
                    tx.send(walker.walk(w).expect("a window"))
                        .expect("the accumulator");
                }
            });
            let mut chunks = Vec::new();
            for walked in rx {
                chunks.extend(
                    accumulator
                        .absorb(walked)
                        .into_iter()
                        .map(|job| job.generate()),
                );
            }
            walking.join().expect("the walker");
            chunks
        })
    };
    let mut traces = builder.finish(&logs[cut..]).expect("the last window");
    traces
        .insert_streamed(chunks)
        .expect("every chunk has a placeholder");
    traces
}

fn rows(t: &Table) -> Vec<Vec<FieldElement<GoldilocksField>>> {
    (0..t.main_table.height)
        .map(|r| t.main_table.get_row(r).to_vec())
        .collect()
}

/// Equal tables, row for row — also the six that lay their rows out in
/// `HashMap` order, since every such map in the process hashes with one state
/// (`tables::trace_hash`).
fn same(what: &str, a: &Table, b: &Table) {
    assert_eq!(
        (a.main_table.width, a.main_table.height),
        (b.main_table.width, b.main_table.height),
        "{what}: shape"
    );
    assert!(rows(a) == rows(b), "{what}: rows differ");
}

fn same_list(what: &str, a: &[Table], b: &[Table]) {
    assert_eq!(a.len(), b.len(), "{what}: table count");
    for (i, (x, y)) in a.iter().zip(b).enumerate() {
        same(&format!("{what}[{i}]"), x, y);
    }
}

