/// The padding rule the windowed builder reads (`LAMBDA_VM_BLOCK_CUT_PADDING`).
fn padding() -> CutPadding {
    CutPadding::from_env().expect("the padding rule")
}

/// The whole-run KECCAK_RND table cut into tables of `rows` rows — rows
/// `[k·rows, (k+1)·rows)`, as the block proof splits it — as many as the
/// builder's padding rule counts ([`CutPadding::tables`]) of the table's real
/// rows (up to the last one whose μ is set).
fn split_keccak_rnd(t: &Traces, per: usize) -> Vec<Table> {
    use crate::tables::keccak_rnd::cols::MU;
    t.keccak_rnds
        .iter()
        .flat_map(|table| {
            let width = table.main_table.width;
            let all = rows(table);
            if all.len() <= per {
                return vec![rebuild(&all, width)];
            }
            let keep = match padding() {
                CutPadding::WholeRun => all.len() / per,
                last => {
                    let real = all
                        .iter()
                        .rposition(|row| row[MU] != FieldElement::zero())
                        .map_or(0, |row| row + 1);
                    last.tables(real, per)
                }
            };
            all.chunks(per)
                .take(keep)
                .map(|chunk| rebuild(chunk, width))
                .collect()
        })
        .collect()
}

fn rebuild(rows: &[Vec<FieldElement<GoldilocksField>>], width: usize) -> Table {
    TraceTable::new_main(rows.iter().flatten().copied().collect(), width, 1)
}

/// The whole-run BITWISE without the lookups of the KECCAK_RND rows `split`
/// leaves out, and how many rows that is. A padding row sends KECCAK_RND's byte
/// checks as `ARE_BYTES[0, 0]` (`keccak_rnd::ARE_BYTES_PER_ROW` a row, main's
/// multiplicity fix), and the whole run counts those of its whole padded table.
fn split_bitwise(t: &Traces, split: &[Table]) -> (Table, usize) {
    use crate::tables::{bitwise, keccak_rnd};
    let height = |tables: &[Table]| tables.iter().map(|t| t.main_table.height).sum::<usize>();
    let left_out = height(&t.keccak_rnds) - height(split);
    let mut table = t.bitwise.clone();
    let (row, col) = (bitwise::row_index(0, 0, 0), bitwise::cols::MU_ARE_BYTES);
    let count = table.main_table.get_row(row)[col];
    let lookups = FieldElement::from((left_out * keccak_rnd::ARE_BYTES_PER_ROW) as u64);
    table.main_table.set(row, col, count - lookups);
    (table, left_out)
}

/// A slice of KECCAK_RND rows built from the ops that reach it is that slice of
/// the whole table, wherever the slice cuts an op's 24 rows.
#[test]
fn keccak_rnd_rows_are_slices_of_the_whole_table() {
    use crate::tables::keccak_rnd::{
        KeccakRoundOperation, generate_keccak_rnd_rows, generate_keccak_rnd_trace,
    };
    let ops: Vec<KeccakRoundOperation> = (0..11u64)
        .map(|i| KeccakRoundOperation {
            timestamp: 100 + 3 * i,
            input: core::array::from_fn(|j| i.wrapping_mul(0x9e37_79b9_7f4a_7c15) ^ j as u64),
            output: [0; 25],
        })
        .collect();
    let whole = rows(&generate_keccak_rnd_trace(&ops));
    for (skip, len) in [
        (0, 32),
        (32, 32),
        (50, 64),
        (23, 1),
        (100, 156),
        (256, 0),
        (200, 56),
    ] {
        let slice = rows(&generate_keccak_rnd_rows(&ops, skip, len));
        assert_eq!(slice.len(), len);
        assert!(
            slice[..] == whole[skip..skip + len],
            "rows {skip}..{}",
            skip + len
        );
    }
}

/// ★ With KECCAK_RND cut into chunks, the windowed build streams them and is the
/// whole-run build with KECCAK_RND split the same way, table for table, BITWISE
/// without the left-out rows' lookups ([`split_bitwise`]); at one-cycle windows
/// it did stream some.
#[test]
fn windowed_streams_keccak_rnd_as_the_split_whole_run_table() {
    let max_rows = MaxRowsConfig::small();
    let mut left_out_any = false;
    for name in ["test_keccak", "test_keccak_multi"] {
        let (program, logs) = run(name);
        let mut reference = whole(&program, &logs, &max_rows);
        for per in [32usize, 64, 128] {
            let split = split_keccak_rnd(&reference, per);
            let (bitwise, left_out) = split_bitwise(&reference, &split);
            left_out_any |= left_out > 0;
            for window in [1, 7, 33] {
                let mut builder = WindowedTraceBuilder::new(&program, &[], &max_rows)
                    .expect("the builder")
                    .keccak_rnd_chunks(per)
                    .expect("a chunk size");
                let body = logs.len() - 1;
                let cut = body - body % window;
                let mut chunks = Vec::new();
                for w in logs[..cut].chunks(window) {
                    chunks.extend(builder.push(w).expect("a window"));
                }
                let streamed = chunks
                    .iter()
                    .filter(|c| c.table == StreamTable::KeccakRnd)
                    .count();
                let mut traces = builder.finish(&logs[cut..]).expect("the last window");
                traces.insert_streamed(chunks).expect("placeholders");
                same_list(
                    &format!("{name} KECCAK_RND/{per} window {window}"),
                    &split,
                    &traces.keccak_rnds,
                );
                // One-cycle windows push every cycle but the last, so every
                // chunk the ops fill before the run ends streams.
                let full = split.iter().filter(|t| t.main_table.height == per).count();
                if window == 1 && full > 1 {
                    assert!(streamed > 0, "{name}, rows {per}: none streamed");
                }
                // Every other table is the whole-run one.
                let keccak =
                    std::mem::replace(&mut reference.keccak_rnds, traces.keccak_rnds.clone());
                let whole_bitwise = std::mem::replace(&mut reference.bitwise, bitwise.clone());
                same_traces(&reference, &traces);
                reference.keccak_rnds = keccak;
                reference.bitwise = whole_bitwise;
            }
        }
    }
    assert!(
        left_out_any || padding() == CutPadding::WholeRun,
        "no split left a KECCAK_RND table out"
    );
}

/// With KECCAK, ECSM, ECDAS and COPY built as their cuts at the finish, the
/// windowed build (its streamed ops dropped) is the whole-run build with those
/// four split by the block's split under the build's padding rule, table for table,
/// at every cut size from one row to past the whole table; the other tables
/// are untouched. And a cut that is not a power of two is refused.
#[cfg(feature = "parallel")]
#[test]
fn windowed_builds_the_cut_tables_as_the_split_whole_run_tables() {
    use crate::block_whir::{split_copy, split_ecdas, split_ecsm, split_keccak};
    let max_rows = MaxRowsConfig::small();
    let mut cut_any = [false; 4];
    for name in [
        "test_keccak_multi",
        "test_ecsm",
        "test_ecsm_multi",
        "test_ecsm_split",
        "test_copy_ecalls",
    ] {
        let (program, logs) = run(name);
        for log2 in [0usize, 1, 2, 3, 6] {
            let rows = 1usize << log2;
            let mut want = whole(&program, &logs, &max_rows);
            let counts = [
                want.keccaks.len(),
                want.ecsms.len(),
                want.ecdases.len(),
                want.copies.len(),
            ];
            split_keccak(&mut want, log2, padding());
            split_ecsm(&mut want, log2, padding());
            split_ecdas(&mut want, log2, padding());
            split_copy(&mut want, log2, padding());
            for (any, (before, after)) in cut_any.iter_mut().zip(counts.iter().zip([
                want.keccaks.len(),
                want.ecsms.len(),
                want.ecdases.len(),
                want.copies.len(),
            ])) {
                *any |= after > *before;
            }
            for window in [7, 1000] {
                let (cut, _) = windowed_with(&program, &logs, &max_rows, window, true, |b| {
                    b.drop_streamed_ops()
                        .expect("before any window")
                        .cuts_at_finish(rows, rows, rows, rows)
                        .expect("powers of two")
                });
                same_traces(&want, &cut);
            }
        }
    }
    assert_eq!(
        cut_any, [true; 4],
        "every family was cut into several tables"
    );
    for (keccak, ecsm, ecdas, copy) in [(6, 4, 4, 4), (4, 0, 4, 4), (4, 4, 12, 4), (4, 4, 4, 6)] {
        assert!(
            WindowedTraceBuilder::new(&run("test_keccak").0, &[], &max_rows)
                .expect("the builder")
                .cuts_at_finish(keccak, ecsm, ecdas, copy)
                .is_err(),
            "{keccak}/{ecsm}/{ecdas}/{copy} is refused"
        );
    }
}

/// With KECCAK_RND built as its tables at the finish alone, the windowed build
/// hands none out and is the whole-run build with KECCAK_RND split the same
/// way, table for table, BITWISE without the left-out rows' lookups
