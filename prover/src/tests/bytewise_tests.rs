//! Tests for the BYTEWISE ALU table.

use crate::tables::bytewise::{BytewiseOperation, bus_interactions, cols, generate_bytewise_trace};
use crate::tables::types::{BusId, FE, alu_op};

#[test]
fn test_compute_res() {
    let a = 0xFF00u64;
    let b = 0x0FF0u64;
    assert_eq!(
        BytewiseOperation::new(a, b, alu_op::AND).compute_res(),
        0x0F00
    );
    assert_eq!(
        BytewiseOperation::new(a, b, alu_op::OR).compute_res(),
        0xFFF0
    );
    assert_eq!(
        BytewiseOperation::new(a, b, alu_op::XOR).compute_res(),
        0xF0F0
    );
}

#[test]
fn test_trace_byte_decomposition() {
    // a XOR b across all 8 bytes.
    let a = 0x1122_3344_5566_7788u64;
    let b = 0x00FF_00FF_00FF_00FFu64;
    let trace = generate_bytewise_trace(&[BytewiseOperation::new(a, b, alu_op::XOR)]);
    assert_eq!(trace.main_table.width, cols::NUM_COLUMNS);
    assert_eq!(trace.main_table.height, 4); // padded to min 4

    let row = trace.main_table.get_row(0);
    // Little-endian: byte 0 is the least significant.
    assert_eq!(row[cols::A[0]], FE::from(0x88u64));
    assert_eq!(row[cols::A[7]], FE::from(0x11u64));
    assert_eq!(row[cols::B[0]], FE::from(0xFFu64));
    assert_eq!(row[cols::OP], FE::from(alu_op::XOR as u64));
    // res byte 0 = 0x88 ^ 0xFF = 0x77
    assert_eq!(row[cols::RES[0]], FE::from(0x77u64));
    // res byte 7 = 0x11 ^ 0x00 = 0x11
    assert_eq!(row[cols::RES[7]], FE::from(0x11u64));
    assert_eq!(row[cols::MU], FE::from(1u64));
}

#[test]
fn test_multiplicity_aggregation() {
    let ops = vec![
        BytewiseOperation::new(1, 2, alu_op::AND),
        BytewiseOperation::new(3, 4, alu_op::OR),
        BytewiseOperation::new(1, 2, alu_op::AND),
    ];
    let trace = generate_bytewise_trace(&ops);
    assert_eq!(trace.main_table.height, 4);

    let mut found = false;
    for row_idx in 0..4 {
        let row = trace.main_table.get_row(row_idx);
        if row[cols::A[0]] == FE::from(1u64)
            && row[cols::B[0]] == FE::from(2u64)
            && row[cols::OP] == FE::from(alu_op::AND as u64)
        {
            assert_eq!(row[cols::MU], FE::from(2u64));
            found = true;
        }
    }
    assert!(found, "expected the (1, 2, AND) row with multiplicity 2");
}

#[test]
fn test_bus_interactions_shape() {
    let interactions = bus_interactions();
    // 8 BYTE_ALU senders + 1 ARE_BYTES[μ] sender + 1 ALU receiver.
    assert_eq!(interactions.len(), 10);

    let byte_alu_senders = interactions
        .iter()
        .filter(|i| i.bus_id == u64::from(BusId::ByteAlu) && i.is_sender)
        .count();
    assert_eq!(byte_alu_senders, 8);

    let alu: Vec<_> = interactions
        .iter()
        .filter(|i| i.bus_id == u64::from(BusId::Alu))
        .collect();
    assert_eq!(alu.len(), 1);
    assert!(!alu[0].is_sender, "ALU is a receiver for BYTEWISE");
    assert_eq!(alu[0].values.len(), 4); // [a, b, op, res]
}

/// Splitting: a count above `MU_MAX` spreads over rows that each stay within the
/// bound and together preserve the total; exactly `MU_MAX` still fits one row.
#[test]
fn test_bytewise_rows_split_counts_above_mu_max() {
    use crate::tables::types::{MU_MAX, dedup_rows};
    let op = BytewiseOperation::new(0xF0, 0x3C, alu_op::AND);
    let ops: Vec<_> = std::iter::repeat_n(op.clone(), 2 * MU_MAX as usize + 7).collect();
    let mut rows: Vec<u64> = dedup_rows(&ops).iter().map(|(_, mu)| *mu).collect();
    rows.sort();
    assert_eq!(rows, vec![7, MU_MAX, MU_MAX]);

    let ops: Vec<_> = std::iter::repeat_n(op, MU_MAX as usize).collect();
    assert_eq!(dedup_rows(&ops).len(), 1);
    assert!(dedup_rows::<BytewiseOperation>(&[]).is_empty());

    // The generated trace never holds a μ above the bound.
    let ops: Vec<_> = std::iter::repeat_n(
        BytewiseOperation::new(1, 2, alu_op::XOR),
        MU_MAX as usize + 1,
    )
    .collect();
    let trace = generate_bytewise_trace(&ops);
    let mut total = 0u64;
    for r in 0..trace.num_rows() {
        let mu = trace.get_main(r, cols::MU).to_raw();
        assert!(mu <= MU_MAX);
        total += mu;
    }
    assert_eq!(total, ops.len() as u64);
}

/// Consistency: the BITWISE collector tallies exactly the IS_BYTE[μ] lookups the
/// generated BYTEWISE instances send (each row's μ once, padding rows as μ = 0),
/// across several small instances and for a row split by `MU_MAX`.
#[test]
fn test_bytewise_mu_bound_lookups_match_collector() {
    use crate::tables::bitwise::BitwiseOperationType;
    use crate::tables::trace_builder::collect_bytewise_mu_bounds;
    use crate::tables::types::MU_MAX;
    use std::collections::HashMap;

    let distinct = [
        BytewiseOperation::new(1, 2, alu_op::AND),
        BytewiseOperation::new(0xFF00, 0x0FF0, alu_op::OR),
        BytewiseOperation::new(u64::MAX, 0x1234, alu_op::XOR),
    ];
    let small: Vec<_> = distinct.iter().cycle().take(11).cloned().collect();
    let split: Vec<_> = std::iter::repeat_n(distinct[1].clone(), MU_MAX as usize + 2)
        .chain(distinct.iter().cloned())
        .collect();

    for (ops, chunk) in [(small, 4usize), (split, 1 << 20)] {
        let mut collected: HashMap<(u8, u8), usize> = HashMap::new();
        for b in collect_bytewise_mu_bounds(&ops, chunk) {
            assert!(b.lookup_type == BitwiseOperationType::AreBytes);
            *collected.entry((b.x, b.y)).or_default() += 1;
        }
        let mut expected: HashMap<(u8, u8), usize> = HashMap::new();
        for c in ops.chunks(chunk) {
            let t = generate_bytewise_trace(c);
            for r in 0..t.num_rows() {
                let mu = t.get_main(r, cols::MU).to_raw() as u8;
                *expected.entry((mu, 0)).or_default() += 1;
            }
        }
        assert_eq!(collected, expected, "instances of {chunk}");
    }
}
