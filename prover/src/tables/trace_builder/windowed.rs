/// Every full chunk the run's lists hold that was not handed out yet, its ops
/// gathered out of the windows.
fn chunk_jobs(
    m: &crate::tables::MaxRowsConfig,
    windows: &[WalkedWindow],
    segments: &RoutedSegments,
    e: &mut StreamSkip,
) -> Vec<ChunkJob> {
    let mut jobs = Vec::new();
    macro_rules! full_chunks {
        ($table:expr, $variant:ident, $list:expr, $max:expr, $done:expr) => {{
            let list = $list;
            let len: usize = windows.iter().map(|w| list(w).len()).sum();
            let max = $max;
            while ($done + 1) * max <= len {
                let index = $done;
                jobs.push(ChunkJob {
                    table: $table,
                    index,
                    ops: ChunkOps::$variant(gather(windows, list, index * max..(index + 1) * max)),
                });
                $done += 1;
            }
        }};
    }
    full_chunks!(StreamTable::Cpu, Cpu, list_cpu, m.cpu, e.cpu);
    full_chunks!(
        StreamTable::MemwRegister,
        MemwRegister,
        list_register_rows,
        m.memw_register,
        e.memw_register
    );
    full_chunks!(
        StreamTable::MemwAligned,
        MemwAligned,
        list_aligned,
        m.memw_aligned,
        e.memw_aligned
    );
    full_chunks!(StreamTable::Memw, Memw, list_general, m.memw, e.memw);
    full_chunks!(StreamTable::Load, Load, list_load, m.load, e.load);
    full_chunks!(StreamTable::Lt, Lt, list_lt, m.lt, e.lt);
    full_chunks!(StreamTable::Shift, Shift, list_shift, m.shift, e.shift);
    // KECCAK_RND, cut at `keccak_rnd_rows` rows: a chunk is out once the ops so
    // far cover all of its rows (the run's padding rows only reach its last).
    if e.keccak_rnd_rows > 0 {
        let rows = e.keccak_rnd_rows;
        let len: usize = windows.iter().map(|w| list_keccak(w).len()).sum();
        while (e.keccak_rnd + 1) * rows <= len * 24 {
            let index = e.keccak_rnd;
            let (first, end) = super::keccak_rnd_op_range(index, rows, len);
            jobs.push(ChunkJob {
                table: StreamTable::KeccakRnd,
                index,
                ops: ChunkOps::KeccakRnd {
                    ops: gather(windows, list_keccak, first..end),
                    skip: index * rows - first * 24,
                    rows,
                },
            });
            e.keccak_rnd += 1;
        }
    }
    // STORE's ops are a routing segment, already one list.
    let store = &segments.store_ops;
    while (e.store + 1) * m.store <= store.len() {
        let index = e.store;
        jobs.push(ChunkJob {
            table: StreamTable::Store,
            index,
            ops: ChunkOps::Store(store[index * m.store..(index + 1) * m.store].to_vec()),
        });
        e.store += 1;
    }
    jobs
}

/// A streamed table's ops not yet in a handed-out chunk
/// ([`WindowedTraceBuilder::drop_streamed_ops`]): the windows' lists, moved in
/// whole, of which the first `start` ops of the first have left.
struct Tail<T> {
    parts: VecDeque<Vec<T>>,
    start: usize,
    len: usize,
}

impl<T: Clone> Tail<T> {
    fn new() -> Self {
        Self {
            parts: VecDeque::new(),
            start: 0,
            len: 0,
        }
    }

    fn push(&mut self, part: Vec<T>) {
        if !part.is_empty() {
            self.len += part.len();
            self.parts.push_back(part);
        }
    }

    /// The first `n` ops (at most `len`). A part that is exactly the chunk
    /// moves out whole; a part the chunk uses up is freed.
    fn take(&mut self, n: usize) -> Vec<T> {
        let n = n.min(self.len);
        self.len -= n;
        if self.start == 0 && self.parts.front().is_some_and(|part| part.len() == n) {
            return self.parts.pop_front().unwrap_or_default();
        }
        let mut out = Vec::with_capacity(n);
        while out.len() < n {
            let Some(front) = self.parts.front() else {
                break;
            };
            let want = n - out.len();
            if front.len() - self.start <= want {
                out.extend_from_slice(&front[self.start..]);
                self.parts.pop_front();
                self.start = 0;
            } else {
                out.extend_from_slice(&front[self.start..self.start + want]);
                self.start += want;
            }
        }
        out
    }

    /// (ops not handed out, ops the parts hold).
    fn held(&self) -> (usize, usize) {
        (self.len, self.len + self.start)
    }

    /// The ops not handed out, as one list.
    fn into_vec(mut self) -> Vec<T> {
        if self.start == 0 && self.parts.len() == 1 {
            return self.parts.pop_front().unwrap_or_default();
        }
        let mut out = Vec::with_capacity(self.len);
        for (i, part) in self.parts.into_iter().enumerate() {
            out.extend_from_slice(&part[if i == 0 { self.start } else { 0 }..]);
        }
        out
    }
}

/// The run so far under [`WindowedTraceBuilder::drop_streamed_ops`].
struct Kept {
    cpu: Tail<super::CpuOperation>,
    register_rows: Tail<super::RegRow>,
    aligned: Tail<super::MemwOperation>,
    general: Tail<super::MemwOperation>,
    load: Tail<super::LoadOperation>,
    lt: Tail<super::LtOperation>,
    shift: Tail<super::ShiftOperation>,
    /// Every other walk list, the run so far (the streamed lists' fields stay
    /// empty; the in-walk lookups only hold what is left to count).
    rest: WalkOutputs,
    /// DECODE with the lookups of the CPU ops handed out counted.
    decode: Table,
}

impl Kept {
    fn new(decode: Table) -> Self {
        Self {
            cpu: Tail::new(),
            register_rows: Tail::new(),
            aligned: Tail::new(),
            general: Tail::new(),
            load: Tail::new(),
            lt: Tail::new(),
            shift: Tail::new(),
            rest: WalkOutputs::with_capacity(0),
            decode,
        }
    }

    /// A walked window's lists, appended in run order.
    fn append(&mut self, window: WalkedWindow) {
        let WalkedWindow { cpu_ops, walk } = window;
        let WalkOutputs {
            memw,
            load_ops,
            lt_ops,
            shift_ops,
            bitwise_ops,
            commit_ops,
            keccak_ops,
            blake3_ops,
            blake3_absorb_ops,
            cpu32_ops,
            ecsm_ops,
            ecdas_ops,
            hint_ops,
        } = walk;
        self.cpu.push(cpu_ops);
        self.register_rows.push(memw.register_rows);
        self.aligned.push(memw.aligned);
        self.general.push(memw.general);
        self.load.push(load_ops);
        self.lt.push(lt_ops);
        self.shift.push(shift_ops);
        let rest = &mut self.rest;
        rest.bitwise_ops.extend(bitwise_ops);
        rest.commit_ops.extend(commit_ops);
        rest.keccak_ops.extend(keccak_ops);
        rest.blake3_ops.extend(blake3_ops);
        rest.blake3_absorb_ops.extend(blake3_absorb_ops);
        rest.cpu32_ops.extend(cpu32_ops);
        rest.ecsm_ops.extend(ecsm_ops);
        rest.ecdas_ops.extend(ecdas_ops);
        rest.hint_ops.extend(hint_ops);
    }

    /// The run's lists with the handed-out ops left out, and DECODE.
    fn into_run(self) -> (Vec<super::CpuOperation>, WalkOutputs, Table) {
        let Kept {
            cpu,
            register_rows,
            aligned,
            general,
            load,
            lt,
            shift,
            mut rest,
            decode,
        } = self;
        rest.memw = MemwBuckets {
            register_rows: register_rows.into_vec(),
            aligned: aligned.into_vec(),
            general: general.into_vec(),
        };
        rest.load_ops = load.into_vec();
        rest.lt_ops = lt.into_vec();
        rest.shift_ops = shift.into_vec();
        (cpu.into_vec(), rest, decode)
    }
}

/// [`chunk_jobs`] under [`WindowedTraceBuilder::drop_streamed_ops`]: every full
/// chunk taken out of the tails, and what the table phase reads from its ops
/// counted as it leaves (`counted`, and DECODE in `kept`).
fn tail_jobs(
    m: &crate::tables::MaxRowsConfig,
    stream_memw_lt: bool,
    pc_to_row: &decode::PcToRow,
    kept: &mut Kept,
    segments: &mut RoutedSegments,
    e: &mut StreamSkip,
    counted: &mut PreCounted,
) -> Vec<ChunkJob> {
    let mut jobs = Vec::new();
    macro_rules! take_chunks {
        ($table:expr, $variant:ident, $tail:expr, $max:expr, $done:expr) => {
            take_chunks!($table, $variant, $tail, $max, $done, |ops| {})
        };
        ($table:expr, $variant:ident, $tail:expr, $max:expr, $done:expr, |$ops:ident| $count:block) => {{
            let max = $max;
            while $tail.len >= max {
                let $ops = $tail.take(max);
                $count
                jobs.push(ChunkJob {
                    table: $table,
                    index: $done,
                    ops: ChunkOps::$variant($ops),
                });
                $done += 1;
            }
        }};
    }
    take_chunks!(StreamTable::Cpu, Cpu, kept.cpu, m.cpu, e.cpu, |ops| {
        let pcs: Vec<u64> = ops.iter().map(|op| op.decode.pc).collect();
        decode::update_multiplicities(&mut kept.decode, pc_to_row, &pcs);
        if let Some(op) = ops.iter().rev().find(|op| op.decode.fields.ecall) {
            counted.last_ecall = Some((op.timestamp, op.next_pc));
        }
    });
    take_chunks!(
        StreamTable::MemwRegister,
        MemwRegister,
        kept.register_rows,
        m.memw_register,
        e.memw_register,
        |ops| {
            super::memw_register::collect_bitwise_from_memw_register(&ops, &mut counted.histogram)
        }
    );
    take_chunks!(
        StreamTable::MemwAligned,
        MemwAligned,
        kept.aligned,
        m.memw_aligned,
        e.memw_aligned,
        |ops| {
            let lookups = super::collect_bitwise_from_memw_aligned(&ops);
            counted.histogram.add_ops(&lookups);
            if !stream_memw_lt {
                let lt = super::collect_lt_from_memw_aligned(&ops);
                counted.memw_aligned_lt.extend(lt);
            }
        }
    );
    take_chunks!(
        StreamTable::Memw,
        Memw,
        kept.general,
        m.memw,
        e.memw,
        |ops| {
            if !stream_memw_lt {
                counted.memw_lt.extend(super::collect_lt_from_memw(&ops));
            }
        }
    );
    take_chunks!(StreamTable::Load, Load, kept.load, m.load, e.load);
    take_chunks!(StreamTable::Lt, Lt, kept.lt, m.lt, e.lt, |ops| {
        counted
            .histogram
            .add_ops(&super::collect_bitwise_from_lt(&ops))
    });
    take_chunks!(
        StreamTable::Shift,
        Shift,
        kept.shift,
        m.shift,
        e.shift,
        |ops| {
            counted
                .histogram
                .add_ops(&shift::collect_bitwise_from_shift(&ops))
        }
    );
    // KECCAK_RND's ops stay: KECCAK needs them all.
    if e.keccak_rnd_rows > 0 {
        let rows = e.keccak_rnd_rows;
        let keccak = &kept.rest.keccak_ops;
        while (e.keccak_rnd + 1) * rows <= keccak.len() * 24 {
            let index = e.keccak_rnd;
            let (first, end) = super::keccak_rnd_op_range(index, rows, keccak.len());
            jobs.push(ChunkJob {
                table: StreamTable::KeccakRnd,
                index,
                ops: ChunkOps::KeccakRnd {
                    ops: keccak[first..end].to_vec(),
                    skip: index * rows - first * 24,
                    rows,
                },
            });
            e.keccak_rnd += 1;
        }
    }
    // STORE's ops are a routing segment: its own tail.
    let store = &mut segments.store_ops;
    while store.len() >= m.store {
        let ops: Vec<store::StoreOperation> = store.drain(..m.store).collect();
        for op in &ops {
            counted.histogram.add_ops(&op.collect_bitwise_ops());
        }
        jobs.push(ChunkJob {
            table: StreamTable::Store,
            index: e.store,
            ops: ChunkOps::Store(ops),
        });
        e.store += 1;
    }
    jobs
}

/// `rayon::join` under the `parallel` feature, the two calls in order without
/// it (the prover's guests take it without rayon).
fn join<A: Send, B: Send>(a: impl FnOnce() -> A + Send, b: impl FnOnce() -> B + Send) -> (A, B) {
    #[cfg(feature = "parallel")]
    {
        rayon::join(a, b)
    }
    #[cfg(not(feature = "parallel"))]
    {
        (a(), b())
    }
}

/// The windows' lists concatenated into the run's, once: list by list in
/// parallel, each window's list freed as it is copied.
/// Whether [`concatenate`] copies each list's windows one after another on one
/// thread (`LAMBDA_VM_BUILDER_CONCAT=serial`), the control for the parallel copy
/// that is the default: on block 25368371 it read −0.52 s of base (FAST 417) and
/// replicated in its re-registered band at −0.21 s (FAST 419). Read once. The
/// two give the same lists.
#[cfg(feature = "parallel")]
fn serial_concat() -> bool {
    static SERIAL: std::sync::OnceLock<bool> = std::sync::OnceLock::new();
    *SERIAL.get_or_init(|| {
        std::env::var("LAMBDA_VM_BUILDER_CONCAT").is_ok_and(|v| v.trim() == "serial")
    })
}

fn concatenate(windows: Vec<WalkedWindow>) -> (Vec<super::CpuOperation>, WalkOutputs) {
    /// The windows' lists one after another, in window order. Under `parallel`
    /// each window's part is moved into its own disjoint slice of the output
    /// on a thread of its own: the copy and the first touch of a list of
    /// several GiB are spread over the pool instead of one thread.
    fn cat<T: Send>(parts: Vec<Vec<T>>) -> Vec<T> {
        let total = parts.iter().map(Vec::len).sum();
        let mut out = Vec::with_capacity(total);
        #[cfg(feature = "parallel")]
        if !serial_concat() && parts.len() > 1 {
            let mut slots: Vec<&mut [std::mem::MaybeUninit<T>]> = Vec::with_capacity(parts.len());
            let mut rest = &mut out.spare_capacity_mut()[..total];
            for part in &parts {
                let (head, tail) = rest.split_at_mut(part.len());
                slots.push(head);
                rest = tail;
            }
            parts
                .into_par_iter()
                .zip(slots.into_par_iter())
                .for_each(|(part, slot)| {
                    for (dst, src) in slot.iter_mut().zip(part) {
                        dst.write(src);
                    }
                });
            // SAFETY: the slots tile `0..total` of the spare capacity, and each
            // was written element for element by its part, whose length it has.
            unsafe { out.set_len(total) };
            return out;
        }
        for part in parts {
            out.extend(part);
        }
        out
    }
    let n = windows.len();
    let mut cpu = Vec::with_capacity(n);
    let mut register_rows = Vec::with_capacity(n);
    let mut aligned = Vec::with_capacity(n);
    let mut general = Vec::with_capacity(n);
    let mut load = Vec::with_capacity(n);
    let mut lt = Vec::with_capacity(n);
    let mut shift = Vec::with_capacity(n);
    let mut bitwise = Vec::with_capacity(n);
    let mut commit = Vec::with_capacity(n);
    let mut keccak = Vec::with_capacity(n);
    let mut blake3 = Vec::with_capacity(n);
    let mut blake3_absorb = Vec::with_capacity(n);
    let mut cpu32 = Vec::with_capacity(n);
    let mut ecsm = Vec::with_capacity(n);
    let mut ecdas = Vec::with_capacity(n);
    let mut hint = Vec::with_capacity(n);
    for WalkedWindow { cpu_ops, walk } in windows {
        cpu.push(cpu_ops);
        register_rows.push(walk.memw.register_rows);
        aligned.push(walk.memw.aligned);
        general.push(walk.memw.general);
        load.push(walk.load_ops);
        lt.push(walk.lt_ops);
        shift.push(walk.shift_ops);
        bitwise.push(walk.bitwise_ops);
        commit.push(walk.commit_ops);
        keccak.push(walk.keccak_ops);
        blake3.push(walk.blake3_ops);
        blake3_absorb.push(walk.blake3_absorb_ops);
        cpu32.push(walk.cpu32_ops);
        ecsm.push(walk.ecsm_ops);
        ecdas.push(walk.ecdas_ops);
        hint.push(walk.hint_ops);
    }
    let ((cpu, (register_rows, aligned)), ((general, bitwise), (load, (lt, shift)))) = join(
        || (cat(cpu), join(|| cat(register_rows), || cat(aligned))),
        || {
            join(
                || join(|| cat(general), || cat(bitwise)),
                || join(|| cat(load), || join(|| cat(lt), || cat(shift))),
            )
        },
    );
    let walk = WalkOutputs {
        memw: MemwBuckets {
            register_rows,
            aligned,
            general,
        },
        load_ops: load,
        lt_ops: lt,
        shift_ops: shift,
        bitwise_ops: bitwise,
        commit_ops: cat(commit),
        keccak_ops: cat(keccak),
        blake3_ops: cat(blake3),
        blake3_absorb_ops: cat(blake3_absorb),
        cpu32_ops: cat(cpu32),
        ecsm_ops: cat(ecsm),
        ecdas_ops: cat(ecdas),
        hint_ops: cat(hint),
    };
    (cpu, walk)
}

/// A completed chunk not generated yet: which chunk it is, and its ops.
/// [`generate`](Self::generate) builds the table a whole-run build puts in that
/// slot, with the same function.
pub struct ChunkJob {
    pub table: StreamTable,
    pub index: usize,
    ops: ChunkOps,
}

enum ChunkOps {
    Cpu(Vec<super::CpuOperation>),
    MemwRegister(Vec<super::RegRow>),
    MemwAligned(Vec<super::MemwOperation>),
    Memw(Vec<super::MemwOperation>),
    Load(Vec<super::LoadOperation>),
    Lt(Vec<super::LtOperation>),
    Shift(Vec<super::ShiftOperation>),
    Store(Vec<store::StoreOperation>),
    KeccakRnd {
        ops: Vec<super::keccak::KeccakOperation>,
        skip: usize,
        rows: usize,
    },
}

impl ChunkJob {
    pub fn generate(self) -> StreamedChunk {
        let trace = match &self.ops {
            ChunkOps::Cpu(ops) => cpu::generate_cpu_trace(ops),
            ChunkOps::MemwRegister(ops) => {
                memw_register::generate_memw_register_trace_from_rows(ops)
            }
            ChunkOps::MemwAligned(ops) => memw_aligned::generate_memw_aligned_trace(ops),
            ChunkOps::Memw(ops) => memw::generate_memw_trace(ops),
            ChunkOps::Load(ops) => load::generate_load_trace(ops),
            ChunkOps::Lt(ops) => lt::generate_lt_trace(ops),
            ChunkOps::Shift(ops) => shift::generate_shift_trace(ops),
            ChunkOps::Store(ops) => store::generate_store_trace(ops),
            ChunkOps::KeccakRnd { ops, skip, rows } => {
                let ops: Vec<keccak_rnd::KeccakRoundOperation> = ops
                    .iter()
                    .map(|op| keccak_rnd::KeccakRoundOperation {
                        timestamp: op.timestamp,
                        input: op.input,
                        output: op.output,
                    })
                    .collect();
                keccak_rnd::generate_keccak_rnd_rows(&ops, *skip, *rows)
            }
        };
        StreamedChunk {
            table: self.table,
            index: self.index,
            trace,
        }
    }
}

/// The walk's lists and the routing's segments as the whole-run
/// [`collect_all_ops`](super::collect_all_ops) returns them, HALT finalization
/// included (the run's end).
fn assemble(
    cpu_ops: Vec<super::CpuOperation>,
    walk: WalkOutputs,
    segments: RoutedSegments,
    register_state: &mut RegisterState,
) -> CollectedOps {
    let WalkOutputs {
        memw,
        load_ops,
        mut lt_ops,
        mut shift_ops,
        mut bitwise_ops,
        commit_ops,
        keccak_ops,
        blake3_ops,
        blake3_absorb_ops,
        cpu32_ops,
        ecsm_ops,
        ecdas_ops,
        hint_ops,
    } = walk;
    let MemwBuckets {
        register_rows: mut memw_register_rows,
        aligned: mut memw_aligned_ops,
        general: mut memw_ops,
    } = memw;
    // HALT's register ops land at the end of their buckets, as in
    // `collect_all_ops`.
    let mut halt = MemwBuckets::with_register_capacity(0);
    halt.extend_ops(collect_halt_ops(register_state));
    memw_register_rows.extend(halt.register_rows);
    memw_aligned_ops.extend(halt.aligned);
    memw_ops.extend(halt.general);

    let RoutedSegments {
        branch_ops,
        mul_filter,
        dvrm_filter,
        eq_ops,
        bytewise_ops,
        store_ops,
        shift_cpu32,
        mul_cpu32,
        dvrm_cpu32,
        bitwise_cpu32,
        lt_dvrm_filter,
        lt_dvrm_cpu32,
        mul_dvrm_filter,
        mul_dvrm_cpu32,
    } = segments;
    shift_ops.extend(shift_cpu32);
    bitwise_ops.extend(bitwise_cpu32);
    let mut mul_ops = mul_filter;
    mul_ops.extend(mul_cpu32);
    mul_ops.extend(mul_dvrm_filter);
    mul_ops.extend(mul_dvrm_cpu32);
    let mut dvrm_ops = dvrm_filter;
    dvrm_ops.extend(dvrm_cpu32);
    lt_ops.extend(lt_dvrm_filter);
    lt_ops.extend(lt_dvrm_cpu32);

    CollectedOps {
        cpu_ops,
        memw_ops,
        memw_aligned_ops,
        memw_register_rows,
        load_ops,
        lt_ops,
        shift_ops,
        bitwise_ops,
        branch_ops,
        mul_ops,
        dvrm_ops,
        commit_ops,
        keccak_ops,
        blake3_ops,
        blake3_absorb_ops,
        eq_ops,
        bytewise_ops,
        store_ops,
        cpu32_ops,
        ecsm_ops,
        ecdas_ops,
        hint_ops,
    }
}

impl Traces {
    /// Puts streamed chunks back into the placeholder slots a windowed build's
    /// [`finish`](WindowedTraceBuilder::finish) left — which makes the traces
    /// the whole-run build's. Refuses a chunk for a slot that is not a
    /// placeholder.
    pub fn insert_streamed(&mut self, chunks: Vec<StreamedChunk>) -> Result<(), Error> {
        for chunk in chunks {
            let slots = match chunk.table {
                StreamTable::Cpu => &mut self.cpus,
                StreamTable::MemwRegister => &mut self.memw_registers,
                StreamTable::MemwAligned => &mut self.memw_aligneds,
                StreamTable::Memw => &mut self.memws,
                StreamTable::Load => &mut self.loads,
                StreamTable::Lt => &mut self.lts,
                StreamTable::Shift => &mut self.shifts,
                StreamTable::Store => &mut self.stores,
                StreamTable::KeccakRnd => &mut self.keccak_rnds,
            };
            let len = slots.len();
            let slot = slots.get_mut(chunk.index).ok_or_else(|| {
                Error::Prover(format!(
                    "{:?} chunk {} has no slot ({len} tables)",
                    chunk.table, chunk.index,
                ))
            })?;
            if slot.main_table.width != 0 {
                return Err(Error::Prover(format!(
                    "{:?} chunk {} lands on a slot that is not a placeholder",
                    chunk.table, chunk.index
                )));
            }
            *slot = chunk.trace;
        }
        Ok(())
    }
}
