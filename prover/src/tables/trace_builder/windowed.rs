type Table = TraceTable<GoldilocksField, GoldilocksExtension>;

/// The tables a windowed build streams: those whose op lists grow in
/// execution order from their first element.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum StreamTable {
    Cpu,
    MemwRegister,
    MemwAligned,
    Memw,
    Load,
    Lt,
    Shift,
    Store,
    /// Only when the builder cuts KECCAK_RND into chunks
    /// ([`WindowedTraceBuilder::keccak_rnd_chunks`]).
    KeccakRnd,
}

impl StreamTable {
    pub const ALL: [StreamTable; 9] = [
        StreamTable::Cpu,
        StreamTable::MemwRegister,
        StreamTable::MemwAligned,
        StreamTable::Memw,
        StreamTable::Load,
        StreamTable::Lt,
        StreamTable::Shift,
        StreamTable::Store,
        StreamTable::KeccakRnd,
    ];
}

/// One full chunk of a streamed table: chunk `index` of that table, the same
/// table a whole-run build puts at `Traces::<field>[index]`.
pub struct StreamedChunk {
    pub table: StreamTable,
    pub index: usize,
    pub trace: Table,
}

/// A run's traces, built window by window. See the module docs.
pub struct WindowedTraceBuilder<'a> {
    artifacts: DecodeArtifacts,
    image: HashMap<u64, u8>,
    register_init: Vec<u32>,
    max_rows: crate::tables::MaxRowsConfig,
    private_input: &'a [u8],
    memory_state: MemoryState,
    register_state: RegisterState,
    /// Cycles collected so far: the next window's first cycle.
    cycles: usize,
    /// The walked windows, in run order, kept as they were walked: moved here,
    /// never copied. `finish` concatenates them once, list by list.
    windows: Vec<WalkedWindow>,
    /// The routing's segments (smaller lists), appended per window.
    segments: RoutedSegments,
    emitted: StreamSkip,
    /// The BITWISE lookups of the walked windows' in-walk lookups and MEMW_R
    /// rows, counted as the windows arrive.
    counted: PreCounted,
    stamps: WindowStamps,
    /// [`Self::stream_memw_lt`].
    stream_memw_lt: bool,
    /// [`Self::drop_streamed_ops`]: the run so far, without the handed-out ops
    /// (`windows` stays empty).
    kept: Option<Kept>,
    /// The parts of the lean walk this build uses.
    lean: WalkLean,
    /// With [`WalkLean::decode`], the walk reads each cycle's decode from here,
    /// from the instruction map otherwise.
    decode: Option<DecodeTable>,
    /// With [`WalkLean::walk_counts`], the walker counts the walked windows'
    /// in-walk lookups here; `finish` adds them to the run's.
    walk_counted: Option<Box<bitwise::BitwiseHistogram>>,
}

/// Where a windowed build spent its time, seconds summed over the windows:
/// the walk, the routing (with the window's bookkeeping), and handing the
/// streamed chunks out (`finish` is timed by its caller).
#[derive(Clone, Copy, Debug, Default)]
pub struct WindowStamps {
    pub windows: usize,
    pub walk: f64,
    pub route: f64,
    pub generate: f64,
}

impl<'a> WindowedTraceBuilder<'a> {
    /// A builder for a run of `elf` on `private_input`, chunked at `max_rows`
    /// — the state [`Traces::from_elf_and_logs`] starts from.
    pub fn new(
        elf: &Elf,
        private_input: &'a [u8],
        max_rows: &crate::tables::MaxRowsConfig,
    ) -> Result<Self, Error> {
        let image = build_initial_image(elf, private_input);
        let register_init = register::register_init_from_entry_point(elf.entry_point);
        let mut memory_state = MemoryState::from_image(&image);
        let register_state = RegisterState::from_init(&register_init);
        let artifacts = DecodeArtifacts::from_elf(elf)?;
        let lean = WalkLean::from_env()?;
        let decode = lean
            .decode
            .then(|| DecodeTable::from_instructions(&artifacts.instructions));
        memory_state.lean = lean.memory;
        let walk_counted = lean
            .walk_counts
            .then(|| Box::new(bitwise::BitwiseHistogram::new()));
        Ok(Self {
            artifacts,
            image,
            register_init,
            max_rows: max_rows.clone(),
            private_input,
            memory_state,
            register_state,
            cycles: 0,
            windows: Vec::new(),
            segments: RoutedSegments::default(),
            emitted: StreamSkip::default(),
            counted: PreCounted {
                histogram: bitwise::BitwiseHistogram::new(),
                bitwise_ops: 0,
                memw_register_rows: 0,
                last_ecall: None,
                memw_lt: Vec::new(),
                memw_aligned_lt: Vec::new(),
            },
            stamps: WindowStamps::default(),
            stream_memw_lt: false,
            kept: None,
            lean,
            decode,
            walk_counted,
        })
    }

    /// Walk with these lean parts, whatever `LAMBDA_VM_WALK_LEAN` says (the
    /// tables are the same). Before the first window only.
    #[cfg(test)]
    pub(crate) fn walk_lean(mut self, lean: WalkLean) -> Self {
        assert_eq!(self.cycles, 0, "walk_lean after a window was walked");
        self.decode = lean
            .decode
            .then(|| DecodeTable::from_instructions(&self.artifacts.instructions));
        self.memory_state.lean = lean.memory;
        self.walk_counted = lean
            .walk_counts
            .then(|| Box::new(bitwise::BitwiseHistogram::new()));
        self.lean = lean;
        self
    }

    /// Collects the next window of the run's logs (not the last one: that is
    /// [`finish`](Self::finish)'s) and returns the full chunks it completed.
    ///
    /// A window may be any length; the chunks do not depend on where the
    /// windows fall.
    pub fn push(&mut self, logs: &[Log]) -> Result<Vec<StreamedChunk>, Error> {
        let jobs = self.push_jobs(logs)?;
        #[cfg(feature = "parallel")]
        let jobs = jobs.into_par_iter();
        #[cfg(not(feature = "parallel"))]
        let jobs = jobs.into_iter();
        Ok(jobs.map(ChunkJob::generate).collect())
    }

    /// Like [`push`](Self::push), but hands back each completed chunk as a
    /// [`ChunkJob`] — its ops, copied out — instead of generating it here, so
    /// the caller can generate it on another thread while this one walks the
    /// next window. The chunks are the same.
    pub fn push_jobs(&mut self, logs: &[Log]) -> Result<Vec<ChunkJob>, Error> {
        let (mut walker, mut accumulator) = self.split();
        let walked = walker.walk(logs)?;
        Ok(accumulator.absorb(walked))
    }

    /// Cut KECCAK_RND into tables of `rows` rows — the split a block proof makes
    /// — and hand each full one out as its ops arrive (24 rows an op; the rows
    /// of an op depend on that op alone). `rows` is a power of two, at least 32.
    /// Without this call KECCAK_RND is one table, built by `finish`.
    pub fn keccak_rnd_chunks(mut self, rows: usize) -> Result<Self, Error> {
        if !rows.is_power_of_two() || rows < 32 {
            return Err(Error::Prover(format!(
                "KECCAK_RND chunks of {rows} rows: a power of two of at least 32 is needed"
            )));
        }
        self.emitted.keccak_rnd_rows = rows;
        Ok(self)
    }

    /// Derive each window's phase-3 LT ops (from its MEMW and MEMW_A ops) as the
    /// window arrives, into the window's LT list, so LT's full chunks stream with
    /// them instead of waiting for the run's end.
    ///
    /// ⚠ BLOCK PATH ONLY. The LT ops are the whole-run build's, but in another
    /// order — each window's MEMW-derived ops follow its walk's — so a chunk
    /// holds other ops than the whole-run build's chunk at that index, and LT
    /// deduplicates per chunk. Every LT op is in exactly one chunk with its
    /// whole-run multiplicity summed over the chunks, which is what LT's
    /// constraints and the bus see; the whole-run order (and so every epoch
    /// proof) is untouched. The chunks are a function of the run and the window
    /// length.
    pub fn stream_memw_lt(mut self) -> Self {
        self.stream_memw_lt = true;
        self
    }

    /// Drop each streamed chunk's ops once the chunk is handed out, instead of
    /// keeping every walked window to the run's end (see the module docs): the
    /// builder then holds less than a chunk of each streamed table's ops, plus
    /// the other tables' lists and (without [`Self::stream_memw_lt`]) the
    /// phase-3 LT ops of the MEMW ops it dropped. The tables are the same.
    /// Before the first window only.
    pub fn drop_streamed_ops(mut self) -> Result<Self, Error> {
        if self.cycles > 0 {
            return Err(Error::Prover(
                "drop_streamed_ops after a window was walked".to_string(),
            ));
        }
        self.kept = Some(Kept::new(self.artifacts.decode_trace.clone()));
        Ok(self)
    }

    /// Per streamed table (CPU, MEMW_R, MEMW_A, MEMW, LOAD, LT, SHIFT, STORE),
    /// the ops the builder holds that were not handed out in a chunk, and the
    /// ops its held lists take room for (those plus a part's handed-out head):
    /// under [`Self::drop_streamed_ops`] only; `None` otherwise.
    pub fn held_streamed_ops(&self) -> Option<[(usize, usize); 8]> {
        let kept = self.kept.as_ref()?;
        let store = self.segments.store_ops.len();
        Some([
            kept.cpu.held(),
            kept.register_rows.held(),
            kept.aligned.held(),
            kept.general.held(),
            kept.load.held(),
            kept.lt.held(),
            kept.shift.held(),
            (store, store),
        ])
    }

    /// The time the windows took so far.
    pub fn stamps(&self) -> WindowStamps {
        self.stamps
    }

    /// How many chunks of each streamed table have been handed out.
    pub fn streamed(&self) -> StreamSkip {
        self.emitted
    }

    /// Collects the run's last window and builds every table the windows did
    /// not stream. The streamed chunks' slots hold empty placeholders;
    /// [`Traces::insert_streamed`] puts the chunks back.
    pub fn finish(mut self, logs: &[Log]) -> Result<Traces, Error> {
        // The last window may halt: it is walked here, not by the `Walker`.
        let cpu_ops = match &self.decode {
            Some(table) => super::collect_cpu_ops_from_table(logs, table, self.cycles)?,
            None => super::collect_cpu_ops_from(logs, &self.artifacts.instructions, self.cycles)?,
        };
        self.cycles += logs.len();
        let mut walk = WalkOutputs::with_capacity(cpu_ops.len());
        // The last window's in-walk lookups are listed and counted by the
        // table phase, lean or not.
        collect_ops_from_cpu_into(
            &cpu_ops,
            &mut self.memory_state,
            &mut self.register_state,
            &mut walk,
            InWalk::List,
            None,
        );
        let route = if self.lean.route {
            route_ops_one_pass
        } else {
            route_ops
        };
        self.segments.append(route(&cpu_ops, &walk.cpu32_ops));
        let last = WalkedWindow { cpu_ops, walk };
        super::build_stamps::mark("p0 last window");
        let Self {
            artifacts,
            image,
            register_init,
            max_rows,
            private_input,
            memory_state,
            mut register_state,
            mut windows,
            segments,
            emitted,
            mut counted,
            kept,
            stream_memw_lt,
            walk_counted,
            ..
        } = self;
        // The lookups the walker counted, with the rest.
        if let Some(walk_counted) = walk_counted {
            counted.histogram.merge(&walk_counted);
        }
        let (ops, decode_trace, skip, pre) = match kept {
            None => {
                windows.push(last);
                let (cpu_ops, walk) = concatenate(windows);
                super::build_stamps::mark("p0 concatenate");
                let ops = assemble(cpu_ops, walk, segments, &mut register_state);
                super::build_stamps::mark("p0 assemble");
                (ops, artifacts.decode_trace.clone(), emitted, counted)
            }
            Some(mut kept) => {
                // The last window's ops, its in-walk lookups and its MEMW
                // ops' LT ops are all still to count, as the tails are.
                kept.append(last);
                let (cpu_ops, walk, decode_trace) = kept.into_run();
                super::build_stamps::mark("p0 concatenate");
                let ops = assemble(cpu_ops, walk, segments, &mut register_state);
                super::build_stamps::mark("p0 assemble");
                // With the MEMW-derived LT ops streamed, `memw_lt_done` counts
                // the dropped ops too; without, it is zero and the dropped
                // ops' LT ops are in `counted`.
                let converted = |done: usize, chunks: usize, max: usize| {
                    if !stream_memw_lt {
                        return Ok(done);
                    }
                    done.checked_sub(chunks * max).ok_or_else(|| {
                        Error::Prover(format!(
                            "{chunks} MEMW chunks of {max} were dropped but only {done} ops' LT ops \
                             were derived"
                        ))
                    })
                };
                let skip = StreamSkip {
                    tails: true,
                    memw_lt_done: converted(emitted.memw_lt_done, emitted.memw, max_rows.memw)?,
                    memw_aligned_lt_done: converted(
                        emitted.memw_aligned_lt_done,
                        emitted.memw_aligned,
                        max_rows.memw_aligned,
                    )?,
                    ..emitted
                };
                let pre = PreCounted {
                    bitwise_ops: 0,
                    memw_register_rows: 0,
                    ..counted
                };
                (ops, decode_trace, skip, pre)
            }
        };
        build_traces(
            ops,
            Some(&image),
            &memory_state,
            &register_init,
            decode_trace,
            &artifacts.decode_pc_to_row,
            register_state,
            &max_rows,
            #[cfg(feature = "disk-spill")]
            stark::storage_mode::StorageMode::Ram,
            private_input,
            true,
            false,
            &skip,
            Some(pre),
        )
    }

    /// The builder in its two halves, to run on two threads: the [`Walker`]
    /// walks each window (the state it carries is the walk's), the
    /// [`Accumulator`] keeps each walked window, routes it and hands out the
    /// chunks it completed. Fed the windows in order, the two build exactly
    /// what [`push_jobs`](Self::push_jobs) builds; afterwards
    /// [`finish`](Self::finish) takes the last window as usual.
    pub fn split(&mut self) -> (Walker<'_>, Accumulator<'_>) {
        (
            Walker {
                artifacts: &self.artifacts,
                decode: self.decode.as_ref(),
                in_walk: self.lean.in_walk(),
                counted: self.walk_counted.as_deref_mut(),
                memory_state: &mut self.memory_state,
                register_state: &mut self.register_state,
                cycles: &mut self.cycles,
                windows: &mut self.stamps.windows,
                walk_secs: &mut self.stamps.walk,
            },
            Accumulator {
                lean: self.lean,
                stream_memw_lt: self.stream_memw_lt,
                max_rows: &self.max_rows,
                pc_to_row: &self.artifacts.decode_pc_to_row,
                kept: self.kept.as_mut(),
                windows: &mut self.windows,
                segments: &mut self.segments,
                emitted: &mut self.emitted,
                counted: &mut self.counted,
                route_secs: &mut self.stamps.route,
                handout_secs: &mut self.stamps.generate,
            },
        )
    }
}

/// One window, walked: its CPU ops and what the walk emitted for them.
pub struct WalkedWindow {
    cpu_ops: Vec<super::CpuOperation>,
    walk: WalkOutputs,
}

/// The walk half of a split builder ([`WindowedTraceBuilder::split`]).
pub struct Walker<'b> {
    artifacts: &'b DecodeArtifacts,
    decode: Option<&'b DecodeTable>,
    /// What the walk does with the in-walk lookups ([`WalkLean::in_walk`]);
    /// with [`InWalk::Count`] it counts them into `counted`.
    in_walk: InWalk,
    counted: Option<&'b mut bitwise::BitwiseHistogram>,
    memory_state: &'b mut MemoryState,
    register_state: &'b mut RegisterState,
    cycles: &'b mut usize,
    windows: &'b mut usize,
    walk_secs: &'b mut f64,
}

impl Walker<'_> {
    /// Walks the next window (not the run's last) into fresh lists.
    pub fn walk(&mut self, logs: &[Log]) -> Result<WalkedWindow, Error> {
        // As a whole-run build: only the last cycle may halt.
        if logs.iter().any(|log| log.next_pc == 0) {
            return Err(Error::HaltInNonFinalEpoch);
        }
        let t = std::time::Instant::now();
        let cpu_ops = match self.decode {
            Some(table) => super::collect_cpu_ops_from_table(logs, table, *self.cycles)?,
            None => super::collect_cpu_ops_from(logs, &self.artifacts.instructions, *self.cycles)?,
        };
        *self.cycles += logs.len();
        // Left out, the accumulator counts them (`absorb`).
        let mut walk = WalkOutputs::for_walk(cpu_ops.len(), self.in_walk == InWalk::List);
        collect_ops_from_cpu_into(
            &cpu_ops,
            self.memory_state,
            self.register_state,
            &mut walk,
            self.in_walk,
            self.counted.as_deref_mut(),
        );
        *self.walk_secs += t.elapsed().as_secs_f64();
        *self.windows += 1;
        Ok(WalkedWindow { cpu_ops, walk })
    }
}

/// The accumulating half of a split builder ([`WindowedTraceBuilder::split`]).
pub struct Accumulator<'b> {
    /// The lean parts the builder uses: with [`InWalk::Leave`] the walker left
    /// each window's in-walk lookups out, with `route` the routing is one pass.
    lean: WalkLean,
    stream_memw_lt: bool,
    max_rows: &'b crate::tables::MaxRowsConfig,
    pc_to_row: &'b decode::PcToRow,
    kept: Option<&'b mut Kept>,
    windows: &'b mut Vec<WalkedWindow>,
    segments: &'b mut RoutedSegments,
    emitted: &'b mut StreamSkip,
    counted: &'b mut PreCounted,
    route_secs: &'b mut f64,
    handout_secs: &'b mut f64,
}

impl Accumulator<'_> {
    /// Routes a walked window, keeps it, and hands out the chunks the run's
    /// lists now complete. Windows must come in run order.
    pub fn absorb(&mut self, mut window: WalkedWindow) -> Vec<ChunkJob> {
        let t = std::time::Instant::now();
        if self.stream_memw_lt {
            let walk = &mut window.walk;
            walk.lt_ops
                .extend(super::collect_lt_from_memw(&walk.memw.general));
            walk.lt_ops
                .extend(super::collect_lt_from_memw_aligned(&walk.memw.aligned));
            self.emitted.memw_lt_done += walk.memw.general.len();
            self.emitted.memw_aligned_lt_done += walk.memw.aligned.len();
        }
        let route = if self.lean.route {
            route_ops_one_pass
        } else {
            route_ops
        };
        self.segments
            .append(route(&window.cpu_ops, &window.walk.cpu32_ops));
        // The table phase's dominant BITWISE source, counted now: from the CPU
        // and LOAD ops when the walk left the lookups out (the list is then
        // empty), from the list otherwise.
        if self.lean.in_walk() == InWalk::Leave {
            let histogram = &mut self.counted.histogram;
            window
                .cpu_ops
                .iter()
                .for_each(|op| op.count_bitwise_into(histogram));
            window
                .walk
                .load_ops
                .iter()
                .for_each(|op| op.count_bitwise_into(histogram));
        }
        self.counted.histogram.add_ops(&window.walk.bitwise_ops);
        self.counted.bitwise_ops += window.walk.bitwise_ops.len();
        if let Some(kept) = self.kept.as_deref_mut() {
            // Nothing else reads the in-walk lookups; MEMW_R's rows are
            // counted as their chunks leave.
            drop(std::mem::take(&mut window.walk.bitwise_ops));
            kept.append(window);
            *self.route_secs += t.elapsed().as_secs_f64();
            let t = std::time::Instant::now();
            let jobs = tail_jobs(
                self.max_rows,
                self.stream_memw_lt,
                self.pc_to_row,
                kept,
                self.segments,
                self.emitted,
                self.counted,
            );
            *self.handout_secs += t.elapsed().as_secs_f64();
            jobs
        } else {
            // And the second, MEMW_R.
            super::memw_register::collect_bitwise_from_memw_register(
                &window.walk.memw.register_rows,
                &mut self.counted.histogram,
            );
            self.counted.memw_register_rows += window.walk.memw.register_rows.len();
            self.windows.push(window);
            *self.route_secs += t.elapsed().as_secs_f64();
            let t = std::time::Instant::now();
            let jobs = chunk_jobs(self.max_rows, self.windows, self.segments, self.emitted);
            *self.handout_secs += t.elapsed().as_secs_f64();
            jobs
        }
    }
}

/// `range` of the run's list that `list` picks out of each window, gathered
/// into one vector (the windows' lists concatenate to the run's).
fn gather<T: Clone>(
    windows: &[WalkedWindow],
    list: impl Fn(&WalkedWindow) -> &[T],
    range: std::ops::Range<usize>,
) -> Vec<T> {
    let mut out = Vec::with_capacity(range.len());
    let mut at = 0usize;
    for window in windows {
        let part = list(window);
        let (lo, hi) = (at, at + part.len());
        if hi > range.start && lo < range.end {
            let from = range.start.max(lo) - lo;
            let to = range.end.min(hi) - lo;
            out.extend_from_slice(&part[from..to]);
        }
        at = hi;
        if at >= range.end {
            break;
        }
    }
    out
}

