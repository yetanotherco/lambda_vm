//! A run's traces built window by window, with the big tables' full chunks
//! handed out as soon as their rows exist.
//!
//! A whole-run build ([`Traces::from_elf_and_logs`]) collects every op before it
//! generates any table, so nothing downstream can start until the last cycle is
//! collected. This builder takes the run's logs a window at a time, carries the
//! memory and register state across windows exactly as the whole-run walk
//! carries it across cycles, and emits every FULL chunk of the tables whose op
//! lists grow in execution order — CPU, MEMW_R, MEMW_A, MEMW, LOAD, LT, SHIFT,
//! STORE — the moment it is complete ([`StreamedChunk`]). [`finish`] then runs the
//! whole-run table phase over the same op lists, generating everything that was
//! not streamed.
//!
//! # ★ The same tables as a whole-run build
//!
//! A chunk is streamed only when it is the op slice `[k·max, (k+1)·max)` of its
//! table's FINAL op list, and that list is the whole-run one:
//! - the CPU ops carry the run's timestamps (`collect_cpu_ops_from`), and the walk
//!   is a per-op fold over carried state, so its per-window outputs concatenate
//!   to the whole-run outputs;
//! - the routing's lists are concatenations of segments (a filter over the CPU
//!   ops, then CPU32's dispatch, then what DVRM implies), and each segment is
//!   accumulated on its own ([`RoutedSegments`]) and concatenated in the
//!   whole-run order at the end;
//! - a table is streamed only from its FIRST segment (for LT and SHIFT: the walk's
//!   part, which the whole-run list starts with), so no later op can land in a
//!   streamed chunk;
//! - the chunks are generated by the same functions the table phase uses.
//!
//! Everything that needs the whole run — BITWISE and DECODE multiplicities, the
//! CPU padding count, HALT finalization, PAGE and REGISTER from the final state,
//! the accelerators — is left to [`finish`], which is the whole-run table phase
//! with the streamed chunks' slots skipped ([`StreamSkip`]). So a windowed build is
//! a SCHEDULE, not a different trace: `windowed_builds_the_whole_run_tables`
//! checks every table against [`Traces::from_elf_and_logs`].
//!
//! Row order inside the tables that deduplicate through a `HashMap` (EQ,
//! BYTEWISE, BRANCH, DVRM, LT, MUL) is not reproducible between ANY two builds;
//! their chunks hold the same ops, so the same rows.
//!
//! [`finish`]: WindowedTraceBuilder::finish

