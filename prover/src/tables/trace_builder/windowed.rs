//! A run's traces built window by window, with the big tables' full chunks
//! handed out as soon as their rows exist.
//!
//! A whole-run build ([`Traces::from_elf_and_logs`]) collects every op before it
//! generates any table, so nothing downstream can start until the last cycle is
//! collected. This builder takes the run's logs a window at a time, carries the
//! memory and register state across windows exactly as the whole-run walk
//! carries it across cycles, and emits every FULL chunk of the tables whose op
//! lists grow in execution order — CPU, MEMW_R, MEMW_A, MEMW, LOAD, LT, SHIFT,
//! STORE — the moment it is complete ([`StreamedChunk`]). [`finish`] then runs the
//! whole-run table phase over the same op lists, generating everything that was
//! not streamed.
//!
//! # ★ The same tables as a whole-run build
//!
//! A chunk is streamed only when it is the op slice `[k·max, (k+1)·max)` of its
//! table's FINAL op list, and that list is the whole-run one:
//! - the CPU ops carry the run's timestamps (`collect_cpu_ops_from`), and the walk
//!   is a per-op fold over carried state, so its per-window outputs concatenate
//!   to the whole-run outputs;
//! - the routing's lists are concatenations of segments (a filter over the CPU
//!   ops, then CPU32's dispatch, then what DVRM implies), and each segment is
//!   accumulated on its own ([`RoutedSegments`]) and concatenated in the
//!   whole-run order at the end;
//! - a table is streamed only from its FIRST segment (for LT and SHIFT: the walk's
//!   part, which the whole-run list starts with), so no later op can land in a
//!   streamed chunk;
//! - the chunks are generated by the same functions the table phase uses.
//!
//! Everything that needs the whole run — BITWISE and DECODE multiplicities, the
//! CPU padding count, HALT finalization, PAGE and REGISTER from the final state,
//! the accelerators — is left to [`finish`], which is the whole-run table phase
//! with the streamed chunks' slots skipped ([`StreamSkip`]). So a windowed build is
//! a SCHEDULE, not a different trace: `windowed_builds_the_whole_run_tables`
//! checks every table against [`Traces::from_elf_and_logs`].
//!
//! Row order inside the tables that deduplicate through a `HashMap` (EQ,
//! BYTEWISE, BRANCH, DVRM, LT, MUL) is not reproducible between ANY two builds;
//! their chunks hold the same ops, so the same rows.
//!
//! [`finish`]: WindowedTraceBuilder::finish

use std::collections::HashMap;

use executor::elf::Elf;
use executor::vm::logs::Log;
#[cfg(feature = "parallel")]
use rayon::prelude::*;
use stark::trace::TraceTable;

use super::super::types::{GoldilocksExtension, GoldilocksField};
use super::{
    CollectedOps, DecodeArtifacts, MemoryState, MemwBuckets, RegisterState, RoutedSegments,
    StreamSkip, Traces, build_initial_image, build_traces, collect_cpu_ops_from, collect_halt_ops,
    collect_ops_from_cpu, route_ops,
};
use crate::Error;
use crate::tables::{cpu, load, lt, memw, memw_aligned, memw_register, register, shift, store};

type Table = TraceTable<GoldilocksField, GoldilocksExtension>;

/// The tables a windowed build streams: those whose op lists grow in
/// execution order from their first element.
#[derive(Clone, Copy, Debug, PartialEq, Eq, Hash)]
pub enum StreamTable {
    Cpu,
    MemwRegister,
    MemwAligned,
    Memw,
    Load,
    Lt,
    Shift,
    Store,
}

impl StreamTable {
    pub const ALL: [StreamTable; 8] = [
        StreamTable::Cpu,
        StreamTable::MemwRegister,
        StreamTable::MemwAligned,
        StreamTable::Memw,
        StreamTable::Load,
        StreamTable::Lt,
        StreamTable::Shift,
        StreamTable::Store,
    ];
}

/// One full chunk of a streamed table: chunk `index` of that table, the same
/// table a whole-run build puts at `Traces::<field>[index]`.
pub struct StreamedChunk {
    pub table: StreamTable,
    pub index: usize,
    pub trace: Table,
}

/// A run's traces, built window by window. See the module docs.
pub struct WindowedTraceBuilder<'a> {
    artifacts: DecodeArtifacts,
    image: HashMap<u64, u8>,
    register_init: Vec<u32>,
    max_rows: crate::tables::MaxRowsConfig,
    private_input: &'a [u8],
    memory_state: MemoryState,
    register_state: RegisterState,
    /// Cycles collected so far: the next window's first cycle.
    cycles: usize,
    /// The walk's lists, whole-run so far (the routing's are in `segments`).
    walk: CollectedOps,
    segments: RoutedSegments,
    emitted: StreamSkip,
}

impl<'a> WindowedTraceBuilder<'a> {
    /// A builder for a run of `elf` on `private_input`, chunked at `max_rows`
    /// — the state [`Traces::from_elf_and_logs`] starts from.
    pub fn new(
        elf: &Elf,
        private_input: &'a [u8],
        max_rows: &crate::tables::MaxRowsConfig,
    ) -> Result<Self, Error> {
        let image = build_initial_image(elf, private_input);
        let register_init = register::register_init_from_entry_point(elf.entry_point);
        let memory_state = MemoryState::from_image(&image);
        let register_state = RegisterState::from_init(&register_init);
        Ok(Self {
            artifacts: DecodeArtifacts::from_elf(elf)?,
            image,
            register_init,
            max_rows: max_rows.clone(),
            private_input,
            memory_state,
            register_state,
            cycles: 0,
            walk: CollectedOps::default(),
            segments: RoutedSegments::default(),
            emitted: StreamSkip::default(),
        })
    }

    /// Collects the next window of the run's logs (not the last one: that is
    /// [`finish`](Self::finish)'s) and returns the full chunks it completed.
    ///
    /// A window may be any length; the chunks do not depend on where the
    /// windows fall.
    pub fn push(&mut self, logs: &[Log]) -> Result<Vec<StreamedChunk>, Error> {
        // As a whole-run build: only the last cycle may halt.
        if logs.iter().any(|log| log.next_pc == 0) {
            return Err(Error::HaltInNonFinalEpoch);
        }
        self.collect(logs)?;
        Ok(self.stream())
    }

    /// Collects the run's last window and builds every table the windows did
    /// not stream. The streamed chunks' slots hold empty placeholders;
    /// [`Traces::insert_streamed`] puts the chunks back.
    pub fn finish(mut self, logs: &[Log]) -> Result<Traces, Error> {
        self.collect(logs)?;
        let Self {
            artifacts,
            image,
            register_init,
            max_rows,
            private_input,
            memory_state,
            mut register_state,
            walk,
            segments,
            emitted,
            ..
        } = self;
        let ops = assemble(walk, segments, &mut register_state);
        build_traces(
            ops,
            Some(&image),
            &memory_state,
            &register_init,
            artifacts.decode_trace.clone(),
            &artifacts.decode_pc_to_row,
            register_state,
            &max_rows,
            #[cfg(feature = "disk-spill")]
            stark::storage_mode::StorageMode::Ram,
            private_input,
            true,
            false,
            &emitted,
        )
    }

    /// How many chunks of each streamed table have been handed out.
    pub fn streamed(&self) -> StreamSkip {
        self.emitted
    }

    /// The walk and the routing over one window, appended to the run's lists.
    fn collect(&mut self, logs: &[Log]) -> Result<(), Error> {
        let cpu_ops = collect_cpu_ops_from(logs, &self.artifacts.instructions, self.cycles)?;
        self.cycles += logs.len();
        let (
            memw,
            load_ops,
            lt_ops,
            shift_ops,
            bitwise_ops,
            commit_ops,
            keccak_ops,
            blake3_ops,
            blake3_absorb_ops,
            cpu32_ops,
            ecsm_ops,
            ecdas_ops,
            hint_ops,
        ) = collect_ops_from_cpu(&cpu_ops, &mut self.memory_state, &mut self.register_state);
        self.segments.append(route_ops(&cpu_ops, &cpu32_ops));
        let w = &mut self.walk;
        w.cpu_ops.extend(cpu_ops);
        w.memw_register_rows.extend(memw.register_rows);
        w.memw_aligned_ops.extend(memw.aligned);
        w.memw_ops.extend(memw.general);
        w.load_ops.extend(load_ops);
        w.lt_ops.extend(lt_ops);
        w.shift_ops.extend(shift_ops);
        w.bitwise_ops.extend(bitwise_ops);
        w.commit_ops.extend(commit_ops);
        w.keccak_ops.extend(keccak_ops);
        w.blake3_ops.extend(blake3_ops);
        w.blake3_absorb_ops.extend(blake3_absorb_ops);
        w.cpu32_ops.extend(cpu32_ops);
        w.ecsm_ops.extend(ecsm_ops);
        w.ecdas_ops.extend(ecdas_ops);
        w.hint_ops.extend(hint_ops);
        Ok(())
    }

    /// Every full chunk the lists now hold that was not handed out yet,
    /// generated in parallel.
    fn stream(&mut self) -> Vec<StreamedChunk> {
        let m = &self.max_rows;
        let w = &self.walk;
        let e = &mut self.emitted;
        let mut jobs: Vec<Box<dyn Fn() -> StreamedChunk + Send + Sync + '_>> = Vec::new();
        macro_rules! full_chunks {
            ($table:expr, $list:expr, $max:expr, $done:expr, $generate:expr) => {{
                let list = &$list;
                let max = $max;
                while ($done + 1) * max <= list.len() {
                    let index = $done;
                    jobs.push(Box::new(move || StreamedChunk {
                        table: $table,
                        index,
                        trace: $generate(&list[index * max..(index + 1) * max]),
                    }));
                    $done += 1;
                }
            }};
        }
        full_chunks!(
            StreamTable::Cpu,
            w.cpu_ops,
            m.cpu,
            e.cpu,
            cpu::generate_cpu_trace
        );
        full_chunks!(
            StreamTable::MemwRegister,
            w.memw_register_rows,
            m.memw_register,
            e.memw_register,
            memw_register::generate_memw_register_trace_from_rows
        );
        full_chunks!(
            StreamTable::MemwAligned,
            w.memw_aligned_ops,
            m.memw_aligned,
            e.memw_aligned,
            memw_aligned::generate_memw_aligned_trace
        );
        full_chunks!(
            StreamTable::Memw,
            w.memw_ops,
            m.memw,
            e.memw,
            memw::generate_memw_trace
        );
        full_chunks!(
            StreamTable::Load,
            w.load_ops,
            m.load,
            e.load,
            load::generate_load_trace
        );
        full_chunks!(StreamTable::Lt, w.lt_ops, m.lt, e.lt, lt::generate_lt_trace);
        full_chunks!(
            StreamTable::Shift,
            w.shift_ops,
            m.shift,
            e.shift,
            shift::generate_shift_trace
        );
        full_chunks!(
            StreamTable::Store,
            self.segments.store_ops,
            m.store,
            e.store,
            store::generate_store_trace
        );
        #[cfg(feature = "parallel")]
        let jobs = jobs.into_par_iter();
        #[cfg(not(feature = "parallel"))]
        let jobs = jobs.into_iter();
        jobs.map(|job| job()).collect()
    }
}

/// The walk's lists and the routing's segments as the whole-run
/// [`collect_all_ops`](super::collect_all_ops) returns them, HALT finalization
/// included (the run's end).
fn assemble(
    walk: CollectedOps,
    segments: RoutedSegments,
    register_state: &mut RegisterState,
) -> CollectedOps {
    let CollectedOps {
        cpu_ops,
        mut memw_ops,
        mut memw_aligned_ops,
        mut memw_register_rows,
        load_ops,
        mut lt_ops,
        mut shift_ops,
        mut bitwise_ops,
        commit_ops,
        keccak_ops,
        blake3_ops,
        blake3_absorb_ops,
        cpu32_ops,
        ecsm_ops,
        ecdas_ops,
        hint_ops,
        ..
    } = walk;
    // HALT's register ops land at the end of their buckets, as in
    // `collect_all_ops`.
    let mut halt = MemwBuckets::with_register_capacity(0);
    halt.extend_ops(collect_halt_ops(register_state));
    memw_register_rows.extend(halt.register_rows);
    memw_aligned_ops.extend(halt.aligned);
    memw_ops.extend(halt.general);

    let RoutedSegments {
        branch_ops,
        mul_filter,
        dvrm_filter,
        eq_ops,
        bytewise_ops,
        store_ops,
        shift_cpu32,
        mul_cpu32,
        dvrm_cpu32,
        bitwise_cpu32,
        lt_dvrm_filter,
        lt_dvrm_cpu32,
        mul_dvrm_filter,
        mul_dvrm_cpu32,
    } = segments;
    shift_ops.extend(shift_cpu32);
    bitwise_ops.extend(bitwise_cpu32);
    let mut mul_ops = mul_filter;
    mul_ops.extend(mul_cpu32);
    mul_ops.extend(mul_dvrm_filter);
    mul_ops.extend(mul_dvrm_cpu32);
    let mut dvrm_ops = dvrm_filter;
    dvrm_ops.extend(dvrm_cpu32);
    lt_ops.extend(lt_dvrm_filter);
    lt_ops.extend(lt_dvrm_cpu32);

    CollectedOps {
        cpu_ops,
        memw_ops,
        memw_aligned_ops,
        memw_register_rows,
        load_ops,
        lt_ops,
        shift_ops,
        bitwise_ops,
        branch_ops,
        mul_ops,
        dvrm_ops,
        commit_ops,
        keccak_ops,
        blake3_ops,
        blake3_absorb_ops,
        eq_ops,
        bytewise_ops,
        store_ops,
        cpu32_ops,
        ecsm_ops,
        ecdas_ops,
        hint_ops,
    }
}

impl Traces {
    /// Puts streamed chunks back into the placeholder slots a windowed build's
    /// [`finish`](WindowedTraceBuilder::finish) left — which makes the traces
    /// the whole-run build's. Refuses a chunk for a slot that is not a
    /// placeholder.
    pub fn insert_streamed(&mut self, chunks: Vec<StreamedChunk>) -> Result<(), Error> {
        for chunk in chunks {
            let slots = match chunk.table {
                StreamTable::Cpu => &mut self.cpus,
                StreamTable::MemwRegister => &mut self.memw_registers,
                StreamTable::MemwAligned => &mut self.memw_aligneds,
                StreamTable::Memw => &mut self.memws,
                StreamTable::Load => &mut self.loads,
                StreamTable::Lt => &mut self.lts,
                StreamTable::Shift => &mut self.shifts,
                StreamTable::Store => &mut self.stores,
            };
            let len = slots.len();
            let slot = slots.get_mut(chunk.index).ok_or_else(|| {
                Error::Prover(format!(
                    "{:?} chunk {} has no slot ({len} tables)",
                    chunk.table, chunk.index,
                ))
            })?;
            if slot.main_table.width != 0 {
                return Err(Error::Prover(format!(
                    "{:?} chunk {} lands on a slot that is not a placeholder",
                    chunk.table, chunk.index
                )));
            }
            *slot = chunk.trace;
        }
        Ok(())
    }
}
